# PIE proof: THE RELAY DOG SKIN SWITCHER, LIVE INSIDE THE PROJECT BRAIN.
#
# FOUNDER DIRECTIVE (2026-09-22): "add it in the project brain somewhere I can switch these mascot skins make sure the
# mascot skin and a relay dog in the project brain is 3-D moving around looking around staying at one place but is able
# to switch skins when I click on each skin it should switch skins."
#
# SO THIS HAS TO PROVE THREE THINGS, AND A SCREENSHOT OF A PANEL PROVES NONE OF THEM ON ITS OWN:
#
#   1. IT IS 3D AND LIVE. The dog in the panel is a scene capture of an actor, not an image. Proven by reading the
#      stage's frame counter twice with a wait between: a number that moved is a camera that is running. A still would
#      photograph identically and the counter would sit still.
#   2. IT MOVES AND LOOKS AROUND WITHOUT GOING ANYWHERE. Proven by sampling the body's rotation and location over
#      several seconds: the yaw must change and the location must not.
#   3. CLICKING A SKIN SWITCHES IT. Proven by wearing each skin in turn and photographing the panel each time, with
#      the registry's own answer for what is worn recorded beside the picture.
#
# The figures are voxel placeholders generated by wonderland/Tools/relay_dog_skins.py, built to the founder's ARDEN
# INFERNAL and APOLLO plates. Nothing here is a cooked asset and nothing was imported.
import json
import os

L = unreal.WonderlandUiTestLibrary
H = unreal.WonderlandHudTestLibrary
ROOT = os.path.join(os.path.dirname(CHANNEL), "captures", "zc", "relay_skins")

# Registry order, which is the order the cards are listed in.
SKINS = ["relay_og", "arden_infernal", "apollo", "skeleton_flame", "hagoromo", "celestial_light", "bee"]


def job():
    os.makedirs(ROOT, exist_ok=True)
    for old in os.listdir(ROOT):
        if old.endswith(".jpg"):
            os.remove(os.path.join(ROOT, old))
    les = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    ues = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem)
    RESULT["status"] = "running"
    steps = []
    RESULT["steps"] = steps
    try:
        yield (lambda: ues.get_game_world() is None, 1800)
        L.set_background_throttle_suspended(True)
        les.editor_request_begin_play()
        yield (lambda: ues.get_game_world() is not None, 240)
        yield (lambda: unreal.GameplayStatics.get_player_pawn(ues.get_game_world(), 0) is not None, 120)
        yield 5.0
        world = ues.get_game_world()
        L.focus_game_viewport()
        ui = L.get_ui(world)
        if ui is None:
            RESULT["status"] = "failed"
            RESULT["why"] = "no UI subsystem"
            return

        def shot(label, note=""):
            path = os.path.join(ROOT, "%02d_%s.jpg" % (len(steps), label))
            H.capture_viewport_jpeg(path, 1900, 94)
            steps.append({"step": label, "note": note, "file": path})
            return path

        # ---- open the Project Brain, then the wardrobe inside it
        ui.toggle_project_brain()
        yield 1.6
        RESULT["brain_open"] = bool(ui.is_project_brain_open())
        shot("brain", "the Project Brain as the founder's frame draws it, wardrobe still shut")

        RESULT["skins_opened"] = bool(ui.set_brain_skins_open(True))
        yield 2.0
        RESULT["skins_open"] = bool(ui.is_brain_skins_open())
        shot("wardrobe", "RELAY DOG open over the brain: the live dog at the left, the seven cards at the right")

        # ---- 1. IS THE PICTURE LIVE? Two readings of the stage's frame counter, three seconds apart.
        first = int(ui.get_skin_stage_frame_count())
        yield 3.0
        second = int(ui.get_skin_stage_frame_count())
        RESULT["frames_first"] = first
        RESULT["frames_second"] = second
        RESULT["capture_is_live"] = second > first
        RESULT["frames_per_second_observed"] = round((second - first) / 3.0, 1)

        # ---- 2. DOES IT MOVE WITHOUT GOING ANYWHERE? Sample the body over five seconds.
        stage = None
        for actor in unreal.GameplayStatics.get_all_actors_of_class(world, unreal.WonderlandSkinStage):
            stage = actor
            break
        yaws, spots = [], []
        if stage is not None:
            body = stage.get_body()
            for _ in range(10):
                if body is not None:
                    yaws.append(round(float(body.get_actor_rotation().yaw), 2))
                    at = body.get_actor_location()
                    spots.append((round(at.x, 1), round(at.y, 1)))
                yield 0.5
        RESULT["yaw_samples"] = yaws
        RESULT["yaw_span_degrees"] = round(max(yaws) - min(yaws), 2) if yaws else 0.0
        # LOOKING AROUND: the heading has to change. STAYING PUT: the ground position must not.
        RESULT["looks_around"] = bool(yaws) and (max(yaws) - min(yaws)) > 3.0
        RESULT["stays_in_one_place"] = len(set(spots)) <= 1 if spots else False
        RESULT["stage_shown_skin"] = str(stage.get_shown_skin_id()) if stage is not None else ""
        RESULT["stage_error"] = str(stage.get_last_error()) if stage is not None else "no stage actor"

        # ---- 3. DOES CLICKING A CARD SWITCH THE SKIN? Wear each in turn and photograph the panel.
        worn = []
        for skin in SKINS:
            ok = bool(ui.wear_relay_skin(skin))
            # A figure is read from text and rebuilt, so give the stage a moment and the capture a few frames.
            yield 1.8
            shown = str(stage.get_shown_skin_id()) if stage is not None else ""
            body = stage.get_body() if stage is not None else None
            worn.append({
                "asked": skin,
                "accepted": ok,
                "stage_shows": shown,
                "boxes": int(body.get_box_count()) if body is not None else 0,
                "height_uu": round(float(body.get_figure_height_uu()), 1) if body is not None else 0.0,
                "error": str(stage.get_last_error()) if stage is not None else "",
            })
            shot("wear_%s" % skin, "asked for %s; the stage is showing %s" % (skin, shown))
        RESULT["worn"] = worn
        # EVERY SKIN THE PANEL OFFERS MUST ACTUALLY GO ON. One that does not is a card that lies.
        RESULT["all_skins_worn"] = all(row["accepted"] and row["stage_shows"] == row["asked"] for row in worn)
        # AND THE DOG UNDERNEATH IS THE SAME SIZE IN ALL OF THEM, which is the founder's silhouette rule as a number.
        heights = sorted({row["height_uu"] for row in worn if row["asked"] != "relay_og"})
        RESULT["height_spread_uu"] = round(heights[-1] - heights[0], 1) if heights else 0.0

        # ---- shut it again, and show the brain is unharmed underneath
        ui.set_brain_skins_open(False)
        yield 1.2
        shot("closed", "wardrobe shut: the founder's Project Brain frame exactly as it was")
        RESULT["brain_still_open"] = bool(ui.is_project_brain_open())
        RESULT["status"] = "done"
    finally:
        with open(os.path.join(ROOT, "steps.json"), "w", encoding="utf-8") as fh:
            json.dump(steps, fh, indent=1)
        try:
            les.editor_request_end_play()
            L.set_background_throttle_suspended(False)
        except Exception as exc:
            unreal.log_warning("WLSKIN could not end play: %s" % exc)
