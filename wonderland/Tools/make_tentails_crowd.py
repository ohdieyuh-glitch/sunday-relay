# A REAL CROWD TIER FOR TENTAILS
#
# MEASURED, NOT GUESSED. zc_avatar_scale showed the avatar system scales -- Cherubim and Seraph run 40 inside
# one Server Avatar at 1.973 ms each, 1.20x growth across four times the crowd. With TenTails in the crowd it
# was 1.47x and 133 ms. The reason is component count, not voxel count: one instanced component is one draw
# batch, and
#
#     Cherubim_Small   5,885 boxes /  25 groups
#     Seraph_Small     5,190 boxes /  25 groups
#     TenTails_Small  12,105 boxes / 123 groups
#
# TenTails_Small keeps 123 of its Large tier's 124 groups. Its ten tails carry the SAME eight materials each,
# which is 80 of those groups on its own -- so its "Small" tier cut the voxels and left the draw batches,
# which is the thing that actually costs.
#
# WHAT IS NOT DONE HERE, AND WHY. The obvious saving is to merge the ten tails into one part: 80 groups
# become 8. But each tail carries its own phase and amplitude --
#
#     part tail0 tails ... tail 0.000 6.000
#     part tail1 tails ... tail 0.100 8.000
#     ...
#     part tail9 tails ... tail 0.900 6.000
#
# -- so merging them would swing all ten in lockstep. That is a visible change to how the founder's avatar
# moves, and a performance fix is not allowed to quietly restyle the art.
#
# WHAT IS DONE. The five small materials fold into the three that carry the figure. Per tail:
#
#     crag 186   warm 164   pale 78     <- 428 of 506 boxes, the ones you actually see
#     eyerim 28  stone 26   eyered 17   pupil 5   ember 2     <- 78 boxes of detail
#
# On a crowd figure at distance those five are sub-pixel. Folding them leaves 3 materials a tail, so 30 tail
# groups instead of 80, and the silhouette, the colours and every tail's own motion are untouched.
#
# AND NOTHING IS OVERWRITTEN. This writes a NEW file. TenTails_Small keeps every box it has, so the hero and
# mid tiers are exactly as the founder left them and this is an addition they can adopt or ignore.
from pathlib import Path
import collections

SOURCE = Path(__file__).resolve().parent.parent / "ProjectAvatars" / "TenTails_Small.wlvox"
TARGET = SOURCE.with_name("TenTails_Crowd.wlvox")

#: Small material -> the bulk material that absorbs it. Chosen by colour family so the fold is invisible at
#: crowd distance: the eye parts go to the warm body tone, the stone speckle to the crag it sits in.
FOLD = {
    "eyerim": "pale",
    "eyered": "warm",
    "pupil":  "crag",
    "stone":  "crag",
    "ember":  "warm",
}


def main():
    raw = SOURCE.read_bytes().decode("utf-8", errors="ignore")
    nl = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.split(nl)

    before = collections.Counter()
    for ln in lines:
        f = ln.split()
        if len(f) >= 3 and f[0] == "box":
            before[(f[1], f[2])] += 1

    out, folded = [], 0
    for ln in lines:
        f = ln.split()
        # Only tail boxes fold. The head, body and the rest keep every material they had.
        if len(f) >= 3 and f[0] == "box" and f[1].startswith("tail") and f[2] in FOLD:
            f[2] = FOLD[f[2]]
            out.append(" ".join(f))
            folded += 1
            continue
        if len(f) >= 4 and f[0] == "material" and f[1] in FOLD:
            # The declaration stays: a material nothing references is harmless, and dropping it would
            # renumber indices that the boxes above no longer point at anyway.
            out.append(ln)
            continue
        if ln.startswith("# RELAY") or ln.startswith("# A RELAY"):
            out.append(ln)
            continue
        out.append(ln)

    header = [
        "# TENTAILS -- CROWD TIER. Generated by Tools/make_tentails_crowd.py from TenTails_Small.wlvox.",
        "# The five small tail materials fold into the three that carry the figure, so the ten tails cost 30",
        "# instanced components instead of 80. Every box, every tail's own phase and amplitude, and the",
        "# silhouette are unchanged; only which material a sub-pixel box is grouped under changes.",
        "# TenTails_Small is untouched -- this is an addition, not a replacement.",
    ]
    TARGET.write_bytes(nl.join(header + out).encode("utf-8"))

    after = collections.Counter()
    for ln in (header + out):
        f = ln.split()
        if len(f) >= 3 and f[0] == "box":
            after[(f[1], f[2])] += 1

    tails_before = sum(1 for (part, _m) in before if part.startswith("tail"))
    tails_after = sum(1 for (part, _m) in after if part.startswith("tail"))
    print("boxes           %6d -> %6d   (must be equal)" % (sum(before.values()), sum(after.values())))
    print("groups total    %6d -> %6d" % (len(before), len(after)))
    print("groups on tails %6d -> %6d" % (tails_before, tails_after))
    print("boxes refiled   %6d" % folded)
    print("written: %s" % TARGET)


if __name__ == "__main__":
    main()
