# WONDERLAND -- THE TERRITORY REGISTRY, WRITTEN FROM THE CANON AND FROM NOTHING ELSE.
#
# FOUNDER, 2026-09-25: "DO NOT INVENT THE TERRITORY SPECIALIZATIONS. Audit the existing Wonderland design/world
# files ... If a territory genuinely has no canonical specialization yet, mark it as NEEDS FOUNDER DEFINITION
# rather than silently inventing permanent lore."
#
# So this script does not contain a single specialisation, purpose or landmark of its own. Every one is read
# out of the two canon files, and anything the canon does not state is written into the registry as EMPTY with
# bSpecialisationIsCanon=False, which is what makes the panel say NEEDS FOUNDER DEFINITION in the game.
#
#     WorldDesign/CANON/nations.json   the machine canon, locked 2026-09-17
#     WorldDesign/CANON/NATIONS.md     the prose canon it was written from
#
# WHERE THE CHECKPOINTS STAND is geometry, not lore, and the canon says so itself: nations.json calls its
# bearings "a placement frame and may be moved as data", while "the identities are canon". The positions here
# are read from the same numbers the WORLD was built from -- the neutral core radius, each nation's axis
# bearing as nation_band.py built it, and Dubel Forest's measured belt -- so a checkpoint cannot drift away
# from the ground it is meant to mark.
#
# Run:  python Tools/territory_registry.py           (writes the block into Config/DefaultGame.ini)
#       python Tools/territory_registry.py --print   (prints it and writes nothing)
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CANON_JSON = os.path.join(ROOT, "WorldDesign", "CANON", "nations.json")
CANON_MD = os.path.join(ROOT, "WorldDesign", "CANON", "NATIONS.md")
INI = os.path.join(ROOT, "Config", "DefaultGame.ini")

BEGIN = "; BEGIN WONDERLAND TERRITORY REGISTRY -- generated by wonderland/Tools/territory_registry.py; do not edit by hand"
END = "; END WONDERLAND TERRITORY REGISTRY"
SECTION = "[/Script/Wonderland.WonderlandTerritorySettings]"

#: The axis each nation was actually BUILT along -- WorldDesign/Nations/nation_band.py lines 65, 87, 106, and
#: the same three bearings the navigation proof walks in Tools/editor_jobs/zc_nav_routes.py.
NATION_BEARING = {"ICARUS": 90.0, "NOCTIS": 210.0, "TARTARUS": 330.0}

#: Dubel Forest's belt, measured and recorded in WorldDesign/Districts/dubel_forest.py:72-73 -- 1,230 m to
#: 1,480 m, on an arc of 58 to 122 degrees centred on the Icarus approach.
DUBEL_RADIUS_UU = 126000.0
DUBEL_BEARING = 90.0

#: The Arrival Gate, verbatim from Tools/travel_registry.py:39. Golden Arrival's checkpoint stands where every
#: visitor already stands, rather than at an origin nobody walks to.
ARRIVAL_XY = (0.0, -1460.0)
ARRIVAL_YAW = 90.0

#: Each nation's marker stands just inside its MARCH -- the approach where, in the canon's words, "its identity
#: begins, still reading as Wonderland". Core is 50,000 uu and the march runs to 65,000.
MARCH_STAND_UU = 52500.0


def read_canon():
    with open(CANON_JSON, encoding="utf-8") as f:
        data = json.load(f)
    with open(CANON_MD, encoding="utf-8") as f:
        prose = f.read()
    return data, prose


def sentence_for(prose, nation):
    """The canon's own sentence describing a nation's specialisation, quoted rather than paraphrased."""
    # The prose canon writes each as "**Video game development:** game creation, ..." under a nation heading.
    block = re.split(r"^##+\s", prose, flags=re.M)
    for part in block:
        if part.upper().startswith(nation):
            m = re.search(r"\*\*(.+?)\*\*[:\s]*(.+?)(?:\n\n|\Z)", part, re.S)
            if m:
                # The canon writes the lead-in inside the bold and sometimes carries its own colon or comma
                # into it -- "**Video game development:**", "**Content creation,**". Stripped, so the sentence
                # reads as the canon meant it rather than as "development:: game creation".
                head = m.group(1).strip().rstrip(":,;. ")
                tail = re.sub(r"\s+", " ", m.group(2)).strip().lstrip(":,; ").rstrip(".")
                return ("%s: %s" % (head, tail)).strip()
    return ""


def spoken(text):
    """A canon phrase as a person would read it aloud: first letter up, acronyms left alone.

    str.title() is wrong here and the first run showed why -- it turned the canon's "NPC behaviour testing"
    into "Npc Behaviour Testing" and "API simulation" into "Api Simulation". These are the founder's own
    words; the only thing this changes is the first character.
    """
    clean = str(text).strip()
    return clean[:1].upper() + clean[1:] if clean else clean


def esc(text):
    return str(text).replace('"', "'")


def row(entry):
    return ('+Territories=(Id="{id}",DisplayName="{name}",Specialisation="{spec}",'
            'bSpecialisationIsCanon={canon},Purpose="{purpose}",Description="{desc}",'
            'Landmarks=({landmarks}),Activities=({activities}),'
            'CheckpointXY=(X={x:.6f},Y={y:.6f}),CheckpointYawDeg={yaw:.6f},'
            'Accent=(R={r:.6f},G={g:.6f},B={b:.6f},A=1.000000),DiscoverRadiusUU={radius:.1f},'
            'CanonSource="{source}")').format(
        id=entry["id"], name=esc(entry["name"]), spec=esc(entry["spec"]),
        canon="True" if entry["canon"] else "False",
        purpose=esc(entry["purpose"]), desc=esc(entry["desc"]),
        landmarks=",".join('"%s"' % esc(v) for v in entry["landmarks"]),
        activities=",".join('"%s"' % esc(v) for v in entry["activities"]),
        x=entry["xy"][0], y=entry["xy"][1], yaw=entry["yaw"],
        r=entry["accent"][0], g=entry["accent"][1], b=entry["accent"][2],
        radius=entry["radius"], source=esc(entry["source"]))


def build():
    import math
    data, prose = read_canon()
    out = []

    neutral = data["neutral"]
    out.append({
        "id": "golden_arrival",
        "name": "GOLDEN ARRIVAL",
        # THE CANON GIVES IT A ROLE AND EXPLICITLY NOT A DISCIPLINE. It is written as canon because the canon
        # states it; it is not a "specialisation" because the canon does not call it one.
        "spec": "NEUTRAL GROUND",
        "canon": True,
        "purpose": neutral["role"],
        "desc": "Wonderland's arrival and crossroads. Every nation's approach begins here and none of them owns it.",
        # NAMED PLACES ONLY FROM THE TRAVEL REGISTRY, which took them verbatim from the Lightning-era table.
        "landmarks": ["The Arrival Gate", "Castle Approach", "The Great Spire", "The Grand Clock",
                      "Royal Gardens", "Clock Quarter", "Water Gardens", "Teapot Court"],
        "activities": ["Travel to any offered destination", "Mission Contracts", "Project Brain",
                       "Wonder Web", "Agent terminals"],
        "xy": ARRIVAL_XY, "yaw": ARRIVAL_YAW,
        "accent": (0.96, 0.82, 0.42),
        "radius": float(neutral["core_radius_cm"]),
        "source": "WorldDesign/CANON/nations.json neutral.role",
    })

    palette = {"ICARUS": (0.93, 0.95, 1.00), "NOCTIS": (0.30, 0.32, 0.40), "TARTARUS": (0.86, 0.16, 0.16)}
    for nation in data["nations"]:
        nid = nation["id"]
        bearing = math.radians(NATION_BEARING[nid])
        out.append({
            "id": nid.lower(),
            "name": nid,
            # THE CANON'S OWN WORD, TITLE-CASED. VIDEO_GAME_DEVELOPMENT -> Video Game Development.
            "spec": spoken(nation["specialisation"].replace("_", " ").lower()),
            "canon": True,
            "purpose": sentence_for(prose, nid) or ", ".join(nation["domain"]),
            "desc": nation["feel"],
            # THE ONLY NAMED PLACES INSIDE A NATION are its GVE spaces, which the band pass placed as tagged
            # anchors from this very list. Nothing else in the nations has a proper name yet.
            "landmarks": ["The %s march" % nid.title()] + [spoken(s) for s in nation["gve_spaces"][:4]],
            "activities": [spoken(s) for s in nation["gve_spaces"]],
            "xy": (math.cos(bearing) * MARCH_STAND_UU, math.sin(bearing) * MARCH_STAND_UU),
            "yaw": (NATION_BEARING[nid] + 180.0) % 360.0,
            "accent": palette[nid],
            "radius": float(neutral["march_outer_cm"]) - float(neutral["core_radius_cm"]),
            "source": "WorldDesign/CANON/NATIONS.md + nations.json nations[%s]" % nid,
        })

    for ex in data.get("exceptions", []):
        if ex["id"] != "DUBEL":
            continue
        bearing = math.radians(DUBEL_BEARING)
        out.append({
            "id": "dubel",
            "name": "DUBEL FOREST",
            # EMPTY ON PURPOSE. The canon gives Dubel an existence and an exception rule and says of its
            # geography "not defined in this world lane". It states no specialisation, no discipline and no
            # purpose. The founder asked for exactly this to be marked rather than filled in.
            "spec": "",
            "canon": False,
            "purpose": "",
            "desc": ex["rule"],
            "landmarks": [],
            "activities": [],
            "xy": (math.cos(bearing) * DUBEL_RADIUS_UU, math.sin(bearing) * DUBEL_RADIUS_UU),
            "yaw": (DUBEL_BEARING + 180.0) % 360.0,
            "accent": (0.42, 0.62, 0.40),
            "radius": 22000.0,
            "source": "WorldDesign/CANON/nations.json exceptions[DUBEL] -- no specialisation stated",
        })
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", dest="show", action="store_true")
    args = ap.parse_args()

    entries = build()
    block = [BEGIN] + [row(e) for e in entries] + [END]
    text = "\n".join(block)

    unnamed = [e["name"] for e in entries if not e["canon"]]
    print("%d territories from canon; %d need founder definition%s"
          % (len(entries), len(unnamed), (": " + ", ".join(unnamed)) if unnamed else ""))
    if args.show:
        print(text)
        return 0

    with open(INI, encoding="utf-8") as f:
        ini = f.read()
    if SECTION not in ini:
        ini = ini.rstrip("\n") + "\n\n" + SECTION + "\n" + text + "\n"
    else:
        start = ini.index(BEGIN) if BEGIN in ini else None
        if start is None:
            at = ini.index(SECTION) + len(SECTION)
            ini = ini[:at] + "\n" + text + ini[at:]
        else:
            stop = ini.index(END) + len(END)
            ini = ini[:start] + text + ini[stop:]
    with open(INI, "w", encoding="utf-8", newline="") as f:
        f.write(ini)
    print("wrote %s" % INI)
    return 0


if __name__ == "__main__":
    sys.exit(main())
