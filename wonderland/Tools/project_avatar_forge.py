"""PROJECT AVATARS, REMADE.

FOUNDER (2026-09-23): "The current Project Avatars look terrible ... blocky, simple, toy-like, LEGO-like ... I do
NOT want another small polish pass. REMAKE THEM." Quality bar: the Claude Code 5 and GPT 6 Astra companions.

WHY THE OLD ONES READ AS LEGO, stated before a box is placed, because it decides the whole method:
  1. RESOLUTION. The LARGE forms were built at 8-12 uu voxels on a 5.6 m body. The companions the founder named are
     built at 2.5 uu. A brick a hand-span across is a brick; a brick a fingernail across is a surface.
  2. MASSING. Bodies were single superellipsoid shells with limbs stuck on -- one lump per part. Anatomy that
     flows is several overlapping masses whose boundaries fall inside each other.
  3. STRAIGHT LIMBS. Tails and legs were straight tapering chains. Nothing alive is straight: every tail here is a
     tube along a curved spine, every leg breaks at a joint.
  4. FLAT MATERIALS. One stone. Now stone has a pale ridge tone, a body tone, a dark crevice tone and a warm
     underside, chosen by the surface normal so the creature is lit by its own construction.

Construction primitives still exist -- this is a voxel figure and the plates are voxel art -- but the silhouette
is meant to hide them: overlapping masses, curved spines, joints, tapers, and a voxel small enough that the
edge of a form reads as a contour rather than a step.

Reads from the old generator's Figure class only for the file format and the fit; every form is new.
"""

import argparse
import math
import os
import random

from project_avatar_figures import Figure as BaseFigure, GLOW_SCALE, TARGET_METRES  # noqa: F401

# ============================================================================ helpers

def normalise(v):
    n = math.sqrt(sum(c * c for c in v)) or 1.0
    return tuple(c / n for c in v)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def lerp3(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def aim(direction):
    """Pitch and yaw (degrees) turning a box's local +X toward `direction`, as FVector::Rotation does."""
    x, y, z = normalise(direction)
    return math.degrees(math.atan2(z, math.hypot(x, y))), math.degrees(math.atan2(y, x))


def polyline_at(spine, s):
    """Point and unit tangent at arc fraction s of a polyline."""
    lengths = [0.0]
    for i in range(1, len(spine)):
        lengths.append(lengths[-1] + math.dist(spine[i], spine[i - 1]))
    total = lengths[-1] or 1.0
    target = max(0.0, min(1.0, s)) * total
    i = 1
    while i < len(spine) - 1 and lengths[i] < target:
        i += 1
    span = (lengths[i] - lengths[i - 1]) or 1.0
    w = (target - lengths[i - 1]) / span
    return lerp3(spine[i - 1], spine[i], w), normalise(tuple(spine[i][n] - spine[i - 1][n] for n in range(3)))


def bezier(p0, p1, p2, p3, steps=14):
    """A cubic curve as a polyline, for spines that bend once and settle."""
    out = []
    for k in range(steps + 1):
        t = k / steps
        u = 1.0 - t
        out.append(tuple(u * u * u * p0[n] + 3 * u * u * t * p1[n] + 3 * u * t * t * p2[n] + t * t * t * p3[n] for n in range(3)))
    return out


class Figure(BaseFigure):
    """The old file format and fit, with the organic primitives the remake needs."""

    # ------------------------------------------------------------------ write, with the raised ceiling
    def box(self, part, material, centre, size, pitch=0.0, yaw=0.0, roll=0.0):
        """A material of None is a deliberate gap -- every helper here may leave one, and the base class
        would write the word None into the file, which the engine loader rejects as an undeclared material
        and the whole figure loads as nothing (the first Seraph rendered as 0 boxes for exactly this)."""
        if material is None:
            return
        BaseFigure.box(self, part, material, centre, size, pitch, yaw, roll)

    def write(self, path):
        """The old format; the ceiling matches WonderlandCompanionFigure::MaxBoxes, raised to 40,000 for these."""
        lines = [
            "# %s -- generated by wonderland/Tools/project_avatar_forge.py. Do not hand-edit; change the generator." % self.name,
            "# A PROJECT AVATAR form. Read by the Project Avatar runtime; format in Source/Wonderland/WonderlandCompanionFigure.h.",
            "wlvox 1",
            "voxel %.3f" % self.voxel_uu,
        ]
        for name, kind, rgb, strength in self.materials:
            if kind in ("glow", "add"):
                strength *= GLOW_SCALE
            lines.append("material %s %s %.4f %.4f %.4f %.3f" % (name, kind, rgb[0], rgb[1], rgb[2], strength))
        for name, parent, pivot, motion, a, b in self.parts:
            extra = "" if a is None else (" %.3f" % a) + ("" if b is None else " %.3f" % b)
            lines.append("part %s %s %.3f %.3f %.3f %s%s" % (name, parent, pivot[0], pivot[1], pivot[2], motion, extra))
        for part, material, c, s, r in self.boxes:
            if abs(r[0]) < 1e-4 and abs(r[1]) < 1e-4 and abs(r[2]) < 1e-4:
                lines.append("box %s %s %.3f %.3f %.3f %.3f %.3f %.3f" % (part, material, c[0], c[1], c[2], s[0], s[1], s[2]))
            else:
                lines.append("box %s %s %.3f %.3f %.3f %.3f %.3f %.3f %.2f %.2f %.2f" % (part, material, c[0], c[1], c[2], s[0], s[1], s[2], r[0], r[1], r[2]))
        assert len(self.boxes) <= 40000, (self.name, "boxes", len(self.boxes))
        assert len(self.parts) <= 48, (self.name, "parts", len(self.parts))
        assert len(self.materials) <= 12, (self.name, "materials", len(self.materials))
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(lines) + "\n")
        return len(self.boxes), len(self.parts), len(self.materials)

    # ------------------------------------------------------------- organic
    def tube(self, part_for, material_for, spine, radius_for, tile, depth=None, twist=0.0, jitter=0.0, bulge=None):
        """RINGS OF TILES AROUND A CURVED SPINE. part_for(s), material_for(s, normal), radius_for(s).

        This is what makes a tail a tail and a leg a leg: the cross-section follows a curve, the radius is a
        function along it, and each tile is turned to face outward so the surface is a skin rather than a stack.
        """
        depth = depth or tile * 0.9
        lengths = [0.0]
        for i in range(1, len(spine)):
            lengths.append(lengths[-1] + math.dist(spine[i], spine[i - 1]))
        total = lengths[-1] or 1.0
        s = 0.0
        ring = 0
        while s <= 1.0 + 1e-6:
            centre, tangent = polyline_at(spine, s)
            helper = (0.0, 0.0, 1.0) if abs(tangent[2]) < 0.9 else (1.0, 0.0, 0.0)
            u = normalise(cross(tangent, helper))
            v = cross(tangent, u)
            r = radius_for(s) * (bulge(s) if bulge else 1.0)
            if r <= 0.05:
                s += tile * 0.9 / total
                ring += 1
                continue
            around = max(4, int(round(2.0 * math.pi * r / tile)))
            phase = twist * s * 2.0 * math.pi + (ring % 2) * math.pi / around
            step = min(tile * 1.15, 2.0 * math.pi * r / around)
            for k in range(around):
                ang = phase + 2.0 * math.pi * k / around
                normal = tuple(math.cos(ang) * u[n] + math.sin(ang) * v[n] for n in range(3))
                point = tuple(centre[n] + normal[n] * r for n in range(3))
                if jitter:
                    point = tuple(point[n] + (self.rng.random() - 0.5) * jitter for n in range(3))
                material = material_for(s, normal)
                if material is None:
                    continue
                pitch, yaw = aim(normal)
                self.box(part_for(s), material, point, (depth, step * 1.08, tile * 1.08), pitch, yaw, (self.rng.random() - 0.5) * 8.0)
            s += tile * 0.9 / total
            ring += 1

    def blob(self, part, material_for, centre, radii, tile, n=2.2, squash=None, jitter=0.0):
        """A SOFT MASS: a superellipsoid skin of outward-facing tiles. material_for(normal) picks the tone."""
        cx, cy, cz = centre
        a, b, c = radii
        e = 2.0 / n
        mean = (a + b + c) / 3.0
        rings = max(4, int(round(math.pi * mean / tile)))
        for ring in range(rings + 1):
            phi = -math.pi / 2.0 + math.pi * ring / rings
            around = max(4, int(round(2.0 * math.pi * max(math.cos(phi), 0.15) * mean / tile)))
            d_theta = 2.0 * math.pi / around
            offset = (ring % 2) * d_theta * 0.5
            for k in range(around):
                theta = offset + d_theta * k
                ux, uy, uz = math.cos(phi) * math.cos(theta), math.cos(phi) * math.sin(theta), math.sin(phi)
                px = a * math.copysign(abs(ux) ** e, ux)
                py = b * math.copysign(abs(uy) ** e, uy)
                pz = c * math.copysign(abs(uz) ** e, uz)
                if squash:
                    px, py, pz = squash(px, py, pz)
                normal = normalise((px / (a * a), py / (b * b), pz / (c * c)))
                material = material_for(normal)
                if material is None:
                    continue
                w = 1.0 + (self.rng.uniform(-jitter, jitter) if jitter else 0.0)
                pitch, yaw = aim(normal)
                self.box(part, material, (cx + px, cy + py, cz + pz), (tile * 0.9, tile * 1.12 * w, tile * 1.12 * w), pitch, yaw, 0.0)

    def eye_socket(self, part, centre, facing, radius, sclera, iris, pupil, rim, ring_r=None, glow=None):
        """A HOUSED EYE: a raised rim ring, a domed sclera, a bright iris, a dark pupil, facing a direction."""
        f = normalise(facing)
        helper = (0.0, 0.0, 1.0) if abs(f[2]) < 0.9 else (1.0, 0.0, 0.0)
        ax = normalise(cross(helper, f))
        ay = cross(f, ax)
        tile = max(0.5, radius * 0.17)
        ring_r = ring_r or radius * 1.28

        def at(u, v, push):
            return tuple(centre[n] + ax[n] * u + ay[n] * v + f[n] * push for n in range(3))

        # the rim: a ring of stone standing proud
        around = max(10, int(round(2.0 * math.pi * ring_r / tile)))
        for k in range(around):
            a = 2.0 * math.pi * k / around
            p = at(math.cos(a) * ring_r, math.sin(a) * ring_r, radius * 0.22)
            pitch, yaw = aim(f)
            self.box(part, rim, p, (tile * 1.5, tile * 1.2, tile * 1.2), pitch, yaw, 0.0)
        # the dome
        steps = max(3, int(round(radius / (tile * 0.75))))
        for iy in range(-steps, steps + 1):
            for ix in range(-steps, steps + 1):
                u, v = ix * tile * 0.8, iy * tile * 0.8
                d = math.hypot(u, v)
                if d > radius:
                    continue
                push = radius * 0.16 + math.sqrt(max(radius * radius - d * d, 0.0)) * 0.34
                if d > radius * 0.66:
                    self.box(part, sclera, at(u, v, push), (tile,) * 3)
                elif d > radius * 0.30:
                    self.box(part, iris, at(u, v, push + tile * 0.15), (tile,) * 3)
                else:
                    self.box(part, pupil, at(u, v, push + tile * 0.30), (tile,) * 3)
        if glow:
            self.box(part, glow, at(0.0, 0.0, radius * 0.55), (tile * 0.8, radius * 1.1, radius * 1.1), *aim(f), 0.0)

    def claw(self, part, material, root, direction, length, base_r, tile):
        """A hooked claw: a short curved tube tapering to a point."""
        d = normalise(direction)
        down = (0.0, 0.0, -1.0)
        spine = bezier(root,
                       tuple(root[n] + d[n] * length * 0.45 for n in range(3)),
                       tuple(root[n] + d[n] * length * 0.85 + down[n] * length * 0.25 for n in range(3)),
                       tuple(root[n] + d[n] * length * 0.95 + down[n] * length * 0.55 for n in range(3)), steps=6)
        self.tube(lambda s: part, lambda s, nrm: material, spine, lambda s: base_r * (1.0 - 0.85 * s), tile * 0.8)

    def spikes(self, part, material, along, count, base_r, length, tile, lean=(0.0, 0.0, 1.0)):
        """A row of short cones along a polyline: crest plates, brow ridges, tail barbs."""
        for k in range(count):
            s = (k + 0.5) / count
            centre, tangent = polyline_at(along, s)
            up = normalise(lean)
            tip = tuple(centre[n] + up[n] * length * (0.6 + 0.4 * math.sin(math.pi * s)) for n in range(3))
            self.tube(lambda t: part, lambda t, nrm: material, [centre, tip], lambda t: base_r * (1.0 - 0.9 * t), tile * 0.85)


# ============================================================================ TEN TAILS

STONE = (0.62, 0.52, 0.42)
STONE_PALE = (0.80, 0.70, 0.58)
