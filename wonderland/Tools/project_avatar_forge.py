    fig.blob("eye", ivory_tone, (centre[0] - R * 0.15, 0.0, centre[2] + R * 0.72), (R * 0.9, R * 1.15, R * 0.34), tile, n=2.4)
    fig.blob("eye", ivory_tone, (centre[0] - R * 0.15, 0.0, centre[2] - R * 0.72), (R * 0.9, R * 1.15, R * 0.30), tile, n=2.4)

