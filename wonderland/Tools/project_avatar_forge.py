    fall = p["fall"]
    eye_z = ground + fall + R * 1.35 + (p["wings"][0][0] * 0.28)
    centre = (0.0, 0.0, eye_z)

    def ivory_tone(normal):
        if fig.rng.random() < 0.04:
            return "gold"
        return "ivory" if normal[2] > -0.2 else "shade"

