def ten_tails(stage):
    p = TEN_TAILS[stage]
    fig = Figure("TEN TAILS PROJECT AVATAR -- %s (remade)" % stage.upper(), seed=2020 + len(stage), voxel_uu=2.5)
    fig.material("stone", "lit", STONE, 1.0)
    fig.material("pale", "lit", STONE_PALE, 1.0)
    fig.material("crag", "lit", STONE_DEEP, 1.0)
    fig.material("warm", "lit", STONE_WARM, 1.0)
    fig.material("eyered", "glow", EYE_RED, 0.9)
    fig.material("eyerim", "glow", EYE_RIM, 0.5)
    fig.material("pupil", "lit", PUPIL, 1.0)
    fig.material("ember", "add", EYE_RED, 0.25)
    fig.material("maw", "lit", (0.05, 0.03, 0.03), 1.0)
    fig.material("tooth", "lit", TOOTH, 1.0)
    tile = p["tile"]
    bl, bw, bh = p["body"]
    hd, hw, hh = p["head"]
    leg, leg_r = p["leg"], p["leg_r"]
    ground = 0.0

    # STONE LIT BY ITS OWN CONSTRUCTION: pale on the ridges facing up, deep in the crevices facing down, warm on
    # the flanks, with a scatter of crag so no surface is one flat colour.
    def hide(normal):
        if fig.rng.random() < 0.07:
            return "crag"
        if normal[2] > 0.55:
            return "pale"
        if normal[2] < -0.35:
            return "crag"
        return "warm" if abs(normal[1]) > 0.6 else "stone"

    # ---------------------------------------------------------------- the body: three overlapping masses
    # A low, heavy quadruped: the chest is the biggest mass and sits forward and high; the belly hangs behind and
    # lower; the haunches rise again at the hips where the tails root. Their boundaries fall inside each other.
    fig.part("root", "-", (0.0, 0.0, 0.0), "spine", 0.9, 0.0)
    # ROUND TWO, AGAINST THE FIRST REMAKE'S OWN FRONT VIEW. The finer voxel stopped it reading as LEGO, but from
    # the front it was a smooth loaf on stubs: the three masses blended into one dome, the shoulders were inside
    # the chest instead of on it, and the legs had no air under them. Four changes, all about silhouette.
    # 1. THE BODY STANDS UP. The chest rode at 0.62 of leg length, so the legs read as stubs under a mass sitting
    #    on the floor. There is air under it now and the existing leg solve simply reaches further to the ground.
    chest_z = ground + leg * 0.72 + bh * 0.42
    fig.blob("root", hide, (bl * 0.18, 0.0, chest_z), (bl * 0.34, bw * 0.54, bh * 0.56), tile, n=2.3, jitter=0.06)
    # 2. A WAIST. The belly was nearly as wide as the chest, which is what fused them into one form; drawn in, so
    #    chest and haunch become two masses with a transition rather than a single tube.
    fig.blob("root", hide, (-bl * 0.12, 0.0, chest_z - bh * 0.12), (bl * 0.40, bw * 0.38, bh * 0.42), tile, n=2.2, jitter=0.06)
    fig.blob("root", hide, (-bl * 0.36, 0.0, chest_z + bh * 0.02), (bl * 0.22, bw * 0.46, bh * 0.46), tile, n=2.4, jitter=0.06)
    # 3. A BRISKET, so the chest has a bottom edge and the front of the creature reads as a front.
    fig.blob("root", hide, (bl * 0.26, 0.0, chest_z - bh * 0.34), (bl * 0.18, bw * 0.34, bh * 0.22), tile, n=2.5, jitter=0.05)
    # 4. SHOULDERS THAT ACTUALLY STAND PROUD. At y=0.40 of the half-width with a 0.16 radius they reached about one
    #    unit past the chest's own 0.52 and were swallowed by it -- the creature had no shoulder at all from the
    #    front. Out to 0.52 and half again as big, they now break the chest's outline where a quadruped's do.
    for sy in (-1.0, 1.0):
        fig.blob("root", hide, (bl * 0.24, sy * bw * 0.52, chest_z + bh * 0.04), (bl * 0.19, bw * 0.24, bh * 0.34), tile, n=2.1)
        # the deltoid, outboard and lower, carrying the shoulder down into the leg instead of stopping in mid-air.
        # Kept small deliberately: at bl*0.13 these four new masses put LARGE at 40,395 boxes against a 40,000 cap,
        # and the cap is a draw-call budget, not a suggestion. The silhouette work pays for itself here rather than
        # by coarsening the whole creature's voxel, which is what stopped it reading as LEGO in the first place.
        fig.blob("root", hide, (bl * 0.20, sy * bw * 0.50, chest_z - bh * 0.26), (bl * 0.10, bw * 0.15, bh * 0.19), tile, n=2.3)
    # the spine crest: a row of plates from the skull to the hips, taller with age
    crest = [(bl * 0.30, 0.0, chest_z + bh * 0.52), (0.0, 0.0, chest_z + bh * 0.46), (-bl * 0.34, 0.0, chest_z + bh * 0.44)]
    fig.spikes("root", "crag", crest, 7 + int(4 * p["crest"]), tile * 1.6, bh * 0.22 * p["crest"] + tile, tile)

    # ---------------------------------------------------------------- the head: fused to the chest
    # No neck. The skull is a broad wedge growing out of the front of the chest, flat on top, with a brow ridge
    # over the eye and the maw cut into the front underside. The eye housing is the front of the face.
    fig.part("head", "root", (bl * 0.42, 0.0, chest_z + bh * 0.10), "head")
    head_c = (bl * 0.42 + hd * 0.42, 0.0, chest_z + bh * 0.10)
    fig.blob("head", hide, head_c, (hd * 0.55, hw * 0.50, hh * 0.50), tile, n=2.6, jitter=0.05)
    # brow ridge over the eye
    brow = [(head_c[0] + hd * 0.42, -hw * 0.30, head_c[2] + hh * 0.36), (head_c[0] + hd * 0.50, 0.0, head_c[2] + hh * 0.42),
            (head_c[0] + hd * 0.42, hw * 0.30, head_c[2] + hh * 0.36)]
    fig.tube(lambda s: "head", lambda s, nrm: "crag" if nrm[2] < 0 else "pale", brow, lambda s: tile * 1.9, tile)
    fig.spikes("head", "crag", brow, 5, tile * 1.2, hh * 0.22, tile, lean=(0.4, 0.0, 1.0))
    # THE EYE: huge, central, housed
    fig.eye_socket("head", (head_c[0] + hd * 0.52, 0.0, head_c[2] + hh * 0.12), (1.0, 0.0, 0.18),
                   p["eye"], "eyerim", "eyered", "pupil", "crag", glow="ember")
    # THE MAW: a dark cavity under the eye, cut into the face, ringed with teeth top and bottom
    maw_c = (head_c[0] + hd * 0.50, 0.0, head_c[2] - hh * 0.28)
    fig.blob("head", lambda n: "maw", maw_c, (hd * 0.18, hw * 0.36, hh * 0.20), tile * 1.1, n=2.4)
    for row, zsign in (("top", 1.0), ("bottom", -1.0)):
        for k in range(p["teeth"]):
            t = (k + 0.5) / p["teeth"]
            y = (t - 0.5) * hw * 0.68
            base = (maw_c[0] + hd * 0.16, y, maw_c[2] + zsign * hh * 0.19)
            tip = (base[0] + tile * 0.4, y, base[2] - zsign * (hh * 0.12 + tile * (1.0 if abs(t - 0.5) > 0.3 else 1.8)))
            fig.tube(lambda s: "head", lambda s, nrm: "tooth", [base, tip], lambda s: tile * 0.9 * (1.0 - 0.8 * s), tile * 0.8)
    # jaw: a lower lip mass so the maw is a mouth and not a hole
    fig.blob("head", hide, (maw_c[0] - hd * 0.05, 0.0, maw_c[2] - hh * 0.26), (hd * 0.30, hw * 0.44, hh * 0.14), tile, n=2.4)

    # ---------------------------------------------------------------- four legs, jointed, splayed, pawed
    for sx, fx in ((1.0, "f"), (-1.0, "r")):
        for sy, fy in ((1.0, "r"), (-1.0, "l")):
            name = "leg_%s%s" % (fx, fy)
            hip = (sx * bl * 0.26, sy * bw * 0.40, chest_z - bh * 0.18)
            phase = 0.0 if (fx == "f") == (fy == "r") else 0.5
            fig.part(name, "root", hip, "stride", phase, 1.0)
            # thigh out and down, shin back to the paw: a real bend at the knee/hock
            knee = (hip[0] + sx * leg * 0.18, hip[1] + sy * leg * 0.22, hip[2] - leg * 0.48)
            shin = "%s_shin" % name
            fig.part(shin, name, knee, "knee", phase, 0.9)
            ankle = (knee[0] - sx * leg * 0.06, knee[1] + sy * leg * 0.06, ground + p["paw"] * 0.55)
            fig.tube(lambda s: name, lambda s, nrm: hide(nrm), bezier(hip, lerp3(hip, knee, 0.4), lerp3(hip, knee, 0.8), knee, 6),
                     lambda s: leg_r * (1.15 - 0.35 * s), tile)
            fig.tube(lambda s: shin, lambda s, nrm: hide(nrm), bezier(knee, lerp3(knee, ankle, 0.3), lerp3(knee, ankle, 0.8), ankle, 6),
                     lambda s: leg_r * (0.85 - 0.25 * s), tile)
            # the knee/hock knob
