        pts = [(0.0, 0.0, rr), (0.0, rr * 0.82, 0.0), (0.0, 0.0, -rr), (0.0, -rr * 0.82, 0.0), (0.0, 0.0, rr)]
        tilt = math.radians(14.0 * (i - (p["rings"] - 1) * 0.5))
