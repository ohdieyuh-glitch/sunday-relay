def main():
    parser = argparse.ArgumentParser(description="Remake the Project Avatar figures.")
    parser.add_argument("--out", default=os.path.join("wonderland", "ProjectAvatars"))
    parser.add_argument("--family", default="all")
    args = parser.parse_args()
