def ue_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def decide(row_id, density, anchors):
    d = density.get(row_id)
    if d is None:
        return "Unassessed", "not in the density audit"
    score = d["sma_60m"] + d["pieces_60m"]
    note = f"audit: {d['sma_60m']} static meshes + {d['pieces_60m']} instanced pieces within 60 m (score {score})"
    status = "Developed" if score >= DEVELOPED_AT else "Available" if score >= AVAILABLE_AT else "InDevelopment"
    if anchors is not None and status in ("Developed", "Available"):
        a = anchors.get(row_id)
        if a is None or not a.get("placed"):
            reason = (a or {}).get("reason", "no anchor result")
            return "InDevelopment", f"{note}; withheld: arrival point not placed ({reason})"
        note += f"; anchor at ({a['location'][0]:.0f}, {a['location'][1]:.0f}, {a['location'][2]:.0f})"
    return status, note


def render(density, anchors):
    lines = [BEGIN]
    for (rid, name, kind, x, y, yaw, desc, district) in CANONICAL:
        status, note = decide(rid, density, anchors)
        lines.append(
            "+Destinations=("
            f'Id="{rid}",DisplayName=INVTEXT("{ue_string(name)}"),Description=INVTEXT("{ue_string(desc)}"),'
            f"Kind={kind},Status={status},District=\"{ue_string(district)}\","
            f"SeedXY=(X={x:.6f},Y={y:.6f}),ArrivalYawDeg={yaw:.6f},MapPackage=\"{MAP_PACKAGE}\","
            f'IconName="{kind.lower()}",DevelopmentNote="{ue_string(note)}")'
        )
    lines.append(END)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", required=True)
    ap.add_argument("--anchors")
    ap.add_argument("--ini", default=str(Path(__file__).resolve().parents[1] / "Config" / "DefaultGame.ini"))
    ap.add_argument("--check", action="store_true", help="exit 1 if the ini block is not what would be written")
    args = ap.parse_args()

    audit = json.loads(Path(args.audit).read_text(encoding="utf-8"))
    density = {d["id"]: d for d in audit["destination_density"]}
    anchors = None
    if args.anchors:
        anchors = {a["id"]: a for a in json.loads(Path(args.anchors).read_text(encoding="utf-8"))["anchors"]}
    block = render(density, anchors)

    ini_path = Path(args.ini)
    text = ini_path.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        new_text = head + block + tail
    else:
        new_text = text.rstrip("\n") + "\n\n" + SECTION + "\n" + block + "\n"
    if args.check:
        sys.exit(0 if new_text == text else 1)
    ini_path.write_text(new_text, encoding="utf-8", newline="\n")
    for (rid, name, *_rest) in CANONICAL:
        status, note = decide(rid, density, anchors)
        print(f"{status:14s} {name:22s} {note}")


if __name__ == "__main__":
    main()
