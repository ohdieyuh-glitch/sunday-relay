// THE CANONICAL RELAY DOG, WALKING — the Unreal half of the locomotion.
//
// WHAT IS HERE AND WHAT IS DELIBERATELY NOT
//
// Everything that can be decided with arithmetic lives in RelayDogStride.h and
// is proven on a laptop. This class does the three things that genuinely need
// an engine, and nothing else:
//
//   1. it FINDS the joints the generator built (dog_v2.py makes BP_RelayDog:
//      Capsule -> Body -> Pivot_<joint> -> Mesh_<joint>_<surface>) and writes
//      the pose onto them;
//   2. it TRACES the ground under each foot so the Dog stands on stairs and
//      slopes rather than through them;
//   3. it carries the third-person camera and the movement component.
//
// THE PARENT CLASS OF BP_RelayDog. The Blueprint is generated by Python, so the
// only way C++ reaches it is by being its parent — dog_v2.py loads this class
// and falls back to plain ACharacter with a LOUD log if it is missing. That
// fallback matters: this project has already shipped a level whose Dogs were
// silently absent because `load_class` returned None and nothing said so.
//
// JOINTS ARE FOUND BY NAME, AND A MISSING ONE IS AN ERROR. The names come from
// dog_canon.JOINTS, so a rename on either side is caught the first time the Dog
// spawns rather than showing up as a limb that never moves.
