def make_cobble(size):
    """Laid setts: rounded stones, recessed mortar, moss in the joints, and the
    contact shadow BAKED into the albedo — which is what actually sells a
    courtyard, more than the normal map does."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    cells = 9
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        for x in range(size):
            u = (x + 0.5) * inv
            f1, f2, cid = voronoi(u, v, cells, SEED, jitter=0.72)
            # crisp joint: how far inside its own stone this pixel sits
            edge = smooth(0.0, 0.055, (f2 - f1))
            dome = edge ** 0.42
            grain = fbm(u, v, 48, 48, 4, SEED + 3)
            fine = fbm(u, v, 160, 160, 2, SEED + 21)

            # A MIXTURE, per the brief: brown, grey and warm slate, drawn per
            # stone so no two neighbours match. One hue family across a whole
            # courtyard is the thing that reads as a printed texture.
            t = 0.32 + 0.28 * (((cid >> 9) & 255) / 255.0)
            fam = (cid >> 21) % 3
            if fam == 0:            # warm brown sandstone
                sr, sg, sb = t * 1.16, t * 0.97, t * 0.76
            elif fam == 1:          # cool grey granite
                sr, sg, sb = t * 0.98, t * 1.00, t * 1.04
            else:                   # warm slate, slightly violet in shadow
                sr, sg, sb = t * 1.04, t * 0.95, t * 0.99
            tone = 0.90 + 0.20 * (((cid >> 17) & 255) / 255.0)
            sr, sg, sb = sr * tone, sg * tone, sb * tone
            # wear on the crown of each stone, grime toward its edge
            wear = 0.88 + 0.30 * dome
            sr, sg, sb = sr * wear, sg * wear, sb * wear
            # grain
            gm = 0.86 + 0.30 * grain
            sr, sg, sb = sr * gm, sg * gm, sb * gm
            sr *= 0.95 + 0.10 * fine
            sg *= 0.95 + 0.10 * fine
            sb *= 0.95 + 0.10 * fine

            # mortar: a pale sandy grout, cooler and duller than the setts.
            # Dark mortar plus baked AO double-counts the shadow and the joints
            # go to black mush at distance.
            mr, mg, mb = 0.30 + 0.08 * grain, 0.29 + 0.08 * grain, 0.26 + 0.07 * grain

            k = smooth(0.06, 0.55, edge)
            r = mr + (sr - mr) * k
            g = mg + (sg - mg) * k
            b = mb + (sb - mb) * k

            # BAKED AO in the joints. Without this the stones read as a printed
            # pattern rather than as objects sitting next to each other.
            ao = 0.52 + 0.48 * smooth(0.0, 0.42, edge)
            r, g, b = r * ao, g * ao, b * ao

            # Moss where water sits — but in DAMP PATCHES, not along every joint.
            # Mossing the whole joint network turns the courtyard into a green
            # net, which is the opposite of the reference's warm stone.
            damp = clamp01((fbm(u, v, 9, 9, 3, SEED + 41) - 0.54) * 3.4)
            mossy = clamp01((1.0 - edge) * 1.10) * damp
            if (cid % 17) == 0:
                mossy = clamp01(mossy + 0.30 * damp)
            r = r + (0.15 - r) * mossy * 0.62
            g = g + (0.31 - g) * mossy * 0.62
            b = b + (0.13 - b) * mossy * 0.62

            # OCCASIONAL CRACKS. A hairline splitting the odd stone, following
            # a wandering line rather than a straight one. Only a few stones get
            # one, which is what makes them read as damage instead of pattern.
            crack = 0.0
            if (cid % 9) == 0:
                cw = math.sin(v * 21.0 + (cid % 17)) * 0.06
                cd = abs((u + cw) - (0.02 + ((cid >> 3) % 100) / 100.0))
                crack = 1.0 - smooth(0.0, 0.006, cd)
                crack *= edge
            r = r * (1.0 - 0.55 * crack)
            g = g * (1.0 - 0.55 * crack)
            b = b * (1.0 - 0.52 * crack)

            i = y * size + x
            alb[i * 3] = _b(r * 255.0)
            alb[i * 3 + 1] = _b(g * 255.0)
            alb[i * 3 + 2] = _b(b * 255.0)
            # worn crowns are smoother; mortar, moss and open cracks are matte
            rv = 0.94 - 0.30 * dome + 0.10 * grain + 0.16 * mossy + 0.18 * crack
            rgh[i] = _b(clamp01(rv) * 255.0)
            hgt[i] = dome * 0.86 + grain * 0.10 + fine * 0.04 - crack * 0.30
    return alb, height_to_normal(hgt, size, 3.4), rgh


def make_ashlar(size):
    """Dressed stone blocks for walls, kerbs and fountain masonry: running bond,
    chamfered arrises, a chisel-textured face."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    rows, cols = 6, 3
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        ry = v * rows
        r_i = int(ry)
        fy = ry - r_i
        shift = 0.5 * (r_i % 2)
        for x in range(size):
            u = (x + 0.5) * inv
            rx = (u + shift) * cols
            c_i = int(rx)
            fx = rx - c_i
            cid = _hash2(c_i % cols, r_i % rows, SEED + 77)
            # distance to the nearest joint, in block-space
            dj = min(fx, 1.0 - fx, fy, 1.0 - fy)
            edge = smooth(0.0, 0.10, dj)
            grain = fbm(u, v, 64, 64, 4, SEED + 5)
            chisel = fbm(u * 1.0, v, 24, 96, 3, SEED + 9)   # tool marks run across
            # AGED WARM LIMESTONE, not concrete grey: the brief asks for pale
            # fantasy stone with pores, stains and worn arrises. Pores are a
            # sparse high-frequency pit field; stains are a slow low-frequency
            # wash that darkens where water has run down the face.
            pore = clamp01((fbm(u, v, 190, 190, 1, SEED + 31) - 0.76) * 3.4)
            stain = fbm(u, v * 0.35, 5, 14, 3, SEED + 37)
            t = 0.56 + 0.16 * (((cid >> 11) & 255) / 255.0)
            wash = 0.90 + 0.16 * stain
            r = t * 1.10 * (0.90 + 0.20 * grain) * (0.95 + 0.09 * chisel) * wash
            g = t * 1.03 * (0.90 + 0.20 * grain) * (0.95 + 0.09 * chisel) * wash
            b = t * 0.90 * (0.90 + 0.20 * grain) * (0.95 + 0.09 * chisel) * (wash * 0.98)
            r *= (1.0 - 0.22 * pore)
            g *= (1.0 - 0.22 * pore)
            b *= (1.0 - 0.20 * pore)
            mr = 0.22 + 0.05 * grain
            k = smooth(0.02, 0.40, edge)
            r = mr + (r - mr) * k
            g = mr + (g - mr) * k
            b = (mr * 0.98) + (b - mr * 0.98) * k
            ao = 0.56 + 0.44 * smooth(0.0, 0.30, edge)
            i = y * size + x
            alb[i * 3] = _b(r * ao * 255.0)
            alb[i * 3 + 1] = _b(g * ao * 255.0)
            alb[i * 3 + 2] = _b(b * ao * 255.0)
            rgh[i] = _b(clamp01(0.86 - 0.16 * edge + 0.12 * grain + 0.20 * pore) * 255.0)
            hgt[i] = edge * 0.80 + grain * 0.14 + chisel * 0.06 - pore * 0.35
    return alb, height_to_normal(hgt, size, 3.0), rgh


def make_sward(size):
    """Meadow: clumped blades rather than a green wash. Two-scale clumping plus a
    fine blade streak, with dry straw and clover breaking the hue."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        for x in range(size):
            u = (x + 0.5) * inv
            clump = fbm(u, v, 10, 10, 3, SEED + 61)
            tuft = fbm(u, v, 40, 40, 3, SEED + 67)
            blade = vnoise(u, v, 24, 200, SEED + 71)      # stretched = blades
            f1, _f2, cid = voronoi(u, v, 22, SEED + 83, jitter=0.9)
            patch = ((cid >> 7) & 255) / 255.0

            # DESATURATE. The first version ran green at roughly 2.5x red, which
            # is a colour no meadow has ever been; on a hundred-metre plane it
            # rendered as a neon slab and became the loudest thing in the frame.
            # Real turf sits near 1.3x with an ochre cast, and it has to survive
            # being the largest area on screen without shouting.
            r = 0.23 + 0.17 * clump + 0.09 * patch * 0.5
            g = 0.29 + 0.18 * clump + 0.09 * tuft
            b = 0.15 + 0.09 * tuft
            # Dry straw in the drier ground, FEATHERED into it. A hard cell
            # threshold stamps visible polygons on the lawn.
            dry = smooth(0.62, 0.94, patch) * smooth(0.30, 0.70, clump) * (0.55 + 0.45 * tuft)
            r += 0.24 * dry
            g += 0.11 * dry
            b += 0.02 * dry
            shade = 0.80 + 0.36 * blade
            i = y * size + x
            alb[i * 3] = _b(r * shade * 255.0)
            alb[i * 3 + 1] = _b(g * shade * 255.0)
            alb[i * 3 + 2] = _b(b * shade * 255.0)
            rgh[i] = _b(clamp01(0.80 + 0.16 * tuft) * 255.0)
            hgt[i] = clump * 0.5 + tuft * 0.32 + blade * 0.18
    return alb, height_to_normal(hgt, size, 2.2), rgh


def make_bark(size):
    """Bark: long vertical fissures with cross-checking, plus lichen."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        for x in range(size):
            u = (x + 0.5) * inv
            # ridged noise stretched along V = vertical fissures
            n = fbm(u, v, 26, 5, 4, SEED + 91)
            ridge = 1.0 - abs(n * 2.0 - 1.0)
            ridge = ridge ** 1.6
            check = fbm(u, v, 8, 34, 3, SEED + 97)        # cross-checking
            fissure = clamp01(ridge * 0.78 + check * 0.30)
            lichen = clamp01((fbm(u, v, 7, 7, 3, SEED + 103) - 0.58) * 3.2)
            # LIGHTEN. At 0.16-0.36 this read as charcoal, so every trunk, post
            # and pergola beam in the world rendered as a black pole. Bark in
            # daylight is a mid warm brown; the fissures carry the darkness.
            t = 0.30 + 0.26 * fissure
            r, g, b = t * 1.16, t * 0.92, t * 0.74
            r = r + (0.42 - r) * lichen * 0.55
            g = g + (0.50 - g) * lichen * 0.55
            b = b + (0.34 - b) * lichen * 0.55
            i = y * size + x
            alb[i * 3] = _b(r * 255.0)
            alb[i * 3 + 1] = _b(g * 255.0)
            alb[i * 3 + 2] = _b(b * 255.0)
            rgh[i] = _b(clamp01(0.90 - 0.16 * fissure) * 255.0)
            hgt[i] = fissure
    return alb, height_to_normal(hgt, size, 3.8), rgh


def make_plaster(size):
    """Lime plaster on the spires: a fine float-trowel tooth, faint patching, and
    a hint of settled dust. Subtle on purpose — it must not read as sandpaper."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        for x in range(size):
            u = (x + 0.5) * inv
            tooth = fbm(u, v, 96, 96, 3, SEED + 111)
            patch = fbm(u, v, 6, 6, 3, SEED + 117)
            pit = clamp01((fbm(u, v, 200, 200, 1, SEED + 121) - 0.72) * 4.0)
            t = 0.90 + 0.10 * patch
            shade = (0.93 + 0.10 * tooth) * (1.0 - 0.22 * pit)
            i = y * size + x
            alb[i * 3] = _b(t * shade * 255.0)
            alb[i * 3 + 1] = _b(t * shade * 0.995 * 255.0)
            alb[i * 3 + 2] = _b(t * shade * 0.975 * 255.0)
            rgh[i] = _b(clamp01(0.52 + 0.22 * tooth + 0.20 * pit) * 255.0)
            hgt[i] = tooth * 0.7 + patch * 0.2 - pit * 0.5
    return alb, height_to_normal(hgt, size, 1.5), rgh


def make_roof(size):
    """Fish-scale roof tiles for the skyline: overlapping scallops in courses."""
    alb = bytearray(size * size * 3)
    rgh = bytearray(size * size)
    hgt = [0.0] * (size * size)
    rows, cols = 10, 8
    inv = 1.0 / size
    for y in range(size):
        v = (y + 0.5) * inv
        ry = v * rows
        r_i = int(ry)
        fy = ry - r_i
        shift = 0.5 * (r_i % 2)
        for x in range(size):
            u = (x + 0.5) * inv
            rx = (u + shift) * cols
            c_i = int(rx)
            fx = rx - c_i
            # A SCALLOP IS A CURVED LOWER EDGE. Shading a straight band at the
            # bottom of a square cell just draws a grid of squares — which is
            # what the first attempt produced. The tile's lower boundary has to
            # BE the arc, and the crescent past it has to be the gap you see
            # down onto the course below.
            dxc = (fx - 0.5) * 2.0
            arc = 1.0 - dxc * dxc
            bottom = 0.70 + 0.30 * arc
            cid = _hash2(c_i % cols, r_i % rows, SEED + 131)
            grain = fbm(u, v, 72, 72, 3, SEED + 137)
            t = 0.72 + 0.24 * (((cid >> 13) & 255) / 255.0)
            if fy <= bottom:
                tl = fy / bottom
                # tiles thicken toward their exposed lip, and the course above
                # casts into their upper edge
                hh = 0.28 + 0.72 * tl
                ao = 0.44 + 0.56 * smooth(0.0, 0.42, tl)
                lip = smooth(0.88, 1.0, tl)
                ao += 0.18 * lip
            else:
                hh = 0.0
                ao = 0.34
            r = t * 1.00 * (0.86 + 0.26 * grain)
            g = t * 0.50 * (0.86 + 0.26 * grain)
            b = t * 0.58 * (0.86 + 0.26 * grain)
            i = y * size + x
            alb[i * 3] = _b(r * ao * 255.0)
            alb[i * 3 + 1] = _b(g * ao * 255.0)
            alb[i * 3 + 2] = _b(b * ao * 255.0)
            rgh[i] = _b(clamp01(0.46 + 0.22 * grain - 0.10 * hh) * 255.0)
            hgt[i] = hh * 0.88 + grain * 0.12
    return alb, height_to_normal(hgt, size, 2.6), rgh


def make_leafcard(size):
    """A CLUSTER OF LEAVES ON A CARD, with a real alpha silhouette.

    Foliage built from opaque boxes and spheres can never stop reading as
    foliage-shaped furniture: what makes a canopy read as leaves is the ragged,
    holed silhouette, and a silhouette is an opacity mask. This paints a spray of
    leaves — each a lens shape with a midrib and veins, on its own petiole off a
    central stem — and returns albedo, normal and the MASK that cuts the card.

    Returns (albedo, normal, mask). The mask is what makes this worth having.
    """
    alb = bytearray(size * size * 3)
    msk = bytearray(size * size)
    hgt = [0.0] * (size * size)
    inv = 1.0 / size

    # a spray: leaves fanned off a stem running up the middle of the card
    leaves = []
    n = 13
    for i in range(n):
        t = (i + 0.5) / n
        side = 1 if i % 2 else -1
        base_v = 0.10 + 0.80 * t
        ang = side * (0.55 + 0.42 * (1.0 - t)) + (_r01(i, 3, SEED + 201) - 0.5) * 0.30
        ln = (0.30 - 0.13 * t) * (0.82 + 0.36 * _r01(i, 7, SEED + 203))
        wd = ln * (0.42 + 0.16 * _r01(i, 11, SEED + 207))
        leaves.append((0.5, base_v, ang, ln, wd, i))
    # a terminal leaf pointing straight up
    leaves.append((0.5, 0.86, 0.0, 0.16, 0.075, 99))

    for y in range(size):
        v = (y + 0.5) * inv
        for x in range(size):
            u = (x + 0.5) * inv
            inside = 0.0
            shade = 0.0
            rib = 0.0
            lid = 0
            for (lu, lv, ang, ln, wd, idx) in leaves:
                du, dv = u - lu, v - lv
                ca, sa = math.cos(ang), math.sin(ang)
                # leaf-local: s along the leaf, t across it
                sL = dv * ca + du * sa
                tL = du * ca - dv * sa
                if sL < 0.0 or sL > ln:
                    continue
                f = sL / ln
                half = wd * 0.5 * (math.sin(math.pi * f) ** 0.62)
                if abs(tL) > half:
                    continue
                inside = 1.0
                lid = idx
                across = abs(tL) / max(half, 1e-5)
                # domed cross-section, midrib and veins
                rib = max(rib, 1.0 - min(1.0, across * 7.0))
                vein = abs(math.sin((f * 9.0 + across * 2.0) * math.pi)) ** 6.0
                shade = max(shade, (1.0 - across * across) * 0.72 + rib * 0.28 + vein * 0.10)
            # the stem
            if abs(u - 0.5) < 0.008 and 0.06 < v < 0.90:
                inside = 1.0
                shade = max(shade, 0.55)
                rib = 1.0
                lid = 50

            i = y * size + x
            if inside <= 0.0:
                msk[i] = 0
                alb[i * 3] = alb[i * 3 + 1] = alb[i * 3 + 2] = 0
                hgt[i] = 0.0
                continue
            msk[i] = 255
            grain = fbm(u, v, 60, 60, 3, SEED + 211)
            # deep in the middle of a leaf, brighter and yellower at its edge:
            # that gradient is what makes a canopy look lit rather than painted
            k = 0.40 + 0.60 * (1.0 - shade)
            base_r = 0.13 + 0.30 * k + 0.10 * ((lid * 37) % 7) / 7.0
            base_g = 0.27 + 0.42 * k
            base_b = 0.10 + 0.16 * k
            gm = 0.88 + 0.26 * grain
            alb[i * 3] = _b(base_r * gm * 255.0)
            alb[i * 3 + 1] = _b(base_g * gm * 255.0)
            alb[i * 3 + 2] = _b(base_b * gm * 255.0)
            hgt[i] = shade * 0.7 + rib * 0.3
    return alb, height_to_normal(hgt, size, 2.4), msk


FAMILIES = (
    ("cobble", make_cobble, 512),
    ("ashlar", make_ashlar, 512),
    ("sward", make_sward, 256),
    ("bark", make_bark, 256),
    ("plaster", make_plaster, 256),
    ("roof", make_roof, 256),
)


def generate(out="/opt/wonderland/textures"):
    """Write the whole set to `out`. Safe to call from inside the UE editor's
    Python: nothing here imports unreal, or anything outside the stdlib."""
    if not os.path.isdir(out):
        os.makedirs(out)
    total = 0
    # Flat defaults. The master material carries albedo/normal/roughness texture
    # inputs for EVERY material; these make them exact no-ops, so a material that
    # does not opt in renders byte-identically to before this pass.
    for nm, px, grey in (("flat_white", (255, 255, 255), False),
                         ("flat_normal", (128, 128, 255), False),
                         ("flat_grey", (128,), True)):
        n = 1 if grey else 3
        buf = bytearray(4 * 4 * n)
        for i in range(4 * 4):
            for c in range(n):
                buf[i * n + c] = px[c]
        total += write_png(os.path.join(out, "T_%s.png" % nm), 4, 4, buf, greyscale=grey)
        print("  T_%s 4x4" % nm)

    for name, fn, size in FAMILIES:
        alb, nrm, rgh = fn(size)
        total += write_png(os.path.join(out, "T_%s_a.png" % name), size, size, alb)
        total += write_png(os.path.join(out, "T_%s_n.png" % name), size, size, nrm)
        total += write_png(os.path.join(out, "T_%s_r.png" % name), size, size, rgh, greyscale=True)
        print("  T_%s_{a,n,r} %dx%d" % (name, size, size))

    # THE LEAF CARD AND ITS MASK. Kept out of FAMILIES because its third map is
    # an opacity MASK rather than a roughness map — it is the only surface here
    # whose point is the shape of its own hole.
    lalb, lnrm, lmsk = make_leafcard(256)
    total += write_png(os.path.join(out, "T_leafcard_a.png"), 256, 256, lalb)
    total += write_png(os.path.join(out, "T_leafcard_n.png"), 256, 256, lnrm)
    total += write_png(os.path.join(out, "T_leafcard_m.png"), 256, 256, lmsk, greyscale=True)
    print("  T_leafcard_{a,n,m} 256x256")
    print("gen-textures: %d families, %.1f KiB, seed 0x%X" % (len(FAMILIES), total / 1024.0, SEED))
    return total


if __name__ == "__main__":
    generate(sys.argv[1] if len(sys.argv) > 1 else "/opt/wonderland/textures")
    sys.exit(0)
