#!/usr/bin/env python3
"""ORIGINAL procedural PBR texture set for Wonderland. stdlib only, deterministic.

WHY THIS EXISTS
---------------
Every surface in Wonderland was a solid colour modulated by 3D world-space noise.
That gets you away from "graybox", but it cannot get you to "premium": a flat
tint has no STRUCTURE, so cobblestone reads as tinted lino no matter how much
the roughness wanders. The reference's ground is individual stones with mortar
between them, worn tops, moss in the joints and baked contact shadow — and that
is texture information, not a shader trick.

Authoring it here rather than downloading it keeps provenance trivially clean:
100% generated by this file from integer hashes, no third-party asset, nothing
to license, nothing to attribute, byte-identical on every rebuild.

WHAT IT WRITES
--------------
For each surface family: albedo (with baked ambient occlusion and per-stone tone
variation), a tangent-space normal derived from the same height field by Sobel,
and a roughness mask. Plus three 4x4 "flat" defaults so the master material can
carry texture inputs that are provably no-ops for every material that does not
opt in — the whole palette keeps its current look unless it asks not to.

Everything tiles. Noise lattices wrap on their period and the Voronoi cell grid
wraps modulo the cell count, so a plaza paved from one 512px sheet has no seam.
"""
import math
import os
import struct
import sys
import zlib

SEED = 0x57ABEE


# --------------------------------------------------------------------------
# PNG
# --------------------------------------------------------------------------
def write_png(path, w, h, pixels, greyscale=False):
    """pixels: flat bytearray of w*h*(1 or 3) samples, row-major, top-down."""
    ch = 1 if greyscale else 3
    raw = bytearray()
    for y in range(h):
        raw.append(0)                       # filter type 0 (None)
        raw += pixels[y * w * ch:(y + 1) * w * ch]
    comp = zlib.compress(bytes(raw), 6)

    def chunk(tag, payload):
        return (struct.pack(">I", len(payload)) + tag + payload
                + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 0 if greyscale else 2, 0, 0, 0)
    blob = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", comp) + chunk(b"IEND", b""))
    with open(path, "wb") as fh:
        fh.write(blob)
    return len(blob)


# --------------------------------------------------------------------------
# noise
# --------------------------------------------------------------------------
def _hash2(x, y, seed):
    n = ((x * 1836311903) ^ (y * 2971215073) ^ (seed * 433494437)) & 0xFFFFFFFF
    n = ((n ^ (n >> 15)) * 2246822519) & 0xFFFFFFFF
    n = ((n ^ (n >> 13)) * 3266489917) & 0xFFFFFFFF
    return (n ^ (n >> 16)) & 0xFFFFFFFF


def _r01(x, y, seed):
    return _hash2(x, y, seed) / 4294967295.0


def vnoise(u, v, fx, fy, seed):
    """Value noise that WRAPS on its own frequency, so every map tiles."""
    x, y = u * fx, v * fy
    x0, y0 = int(x), int(y)
    tx, ty = x - x0, y - y0
    sx = tx * tx * (3.0 - 2.0 * tx)
    sy = ty * ty * (3.0 - 2.0 * ty)
    x1, y1 = (x0 + 1) % fx, (y0 + 1) % fy
    x0, y0 = x0 % fx, y0 % fy
    a = _r01(x0, y0, seed)
    b = _r01(x1, y0, seed)
    c = _r01(x0, y1, seed)
    d = _r01(x1, y1, seed)
    ab = a + (b - a) * sx
    cd = c + (d - c) * sx
    return ab + (cd - ab) * sy


def fbm(u, v, fx, fy, octaves, seed, gain=0.5):
    amp, tot, norm = 1.0, 0.0, 0.0
    for o in range(octaves):
        tot += vnoise(u, v, fx << o, fy << o, seed + o * 101) * amp
        norm += amp
        amp *= gain
    return tot / norm


def voronoi(u, v, cells, seed, jitter=0.78):
    """Nearest / second-nearest jittered cell centre, wrapping modulo `cells`."""
    gx, gy = int(u * cells), int(v * cells)
    f1, f2, cid = 9.0, 9.0, 0
    inv = 1.0 / cells
    off = (1.0 - jitter) * 0.5
    for dy in (-1, 0, 1):
        cy = gy + dy
        wy = cy % cells
        for dx in (-1, 0, 1):
            cx = gx + dx
            wx = cx % cells
            px = (cx + off + jitter * _r01(wx, wy, seed)) * inv
            py = (cy + off + jitter * _r01(wx, wy, seed + 7)) * inv
            d = math.hypot(u - px, v - py)
            if d < f1:
                f2, f1, cid = f1, d, _hash2(wx, wy, seed + 13)
            elif d < f2:
                f2 = d
    return f1, f2, cid


def clamp01(x):
    return 0.0 if x < 0.0 else (1.0 if x > 1.0 else x)


def smooth(e0, e1, x):
    t = clamp01((x - e0) / (e1 - e0)) if e1 != e0 else 0.0
    return t * t * (3.0 - 2.0 * t)


# --------------------------------------------------------------------------
# height -> tangent-space normal (Sobel, wrapping)
# --------------------------------------------------------------------------
def height_to_normal(hmap, size, strength):
    out = bytearray(size * size * 3)
    for y in range(size):
        ym, yp = (y - 1) % size, (y + 1) % size
        r0, r1, r2 = ym * size, y * size, yp * size
        for x in range(size):
            xm, xp = (x - 1) % size, (x + 1) % size
            dx = ((hmap[r0 + xp] + 2.0 * hmap[r1 + xp] + hmap[r2 + xp])
                  - (hmap[r0 + xm] + 2.0 * hmap[r1 + xm] + hmap[r2 + xm]))
            dy = ((hmap[r2 + xm] + 2.0 * hmap[r2 + x] + hmap[r2 + xp])
                  - (hmap[r0 + xm] + 2.0 * hmap[r0 + x] + hmap[r0 + xp]))
            nx, ny, nz = -dx * strength, -dy * strength, 1.0
            inv = 1.0 / math.sqrt(nx * nx + ny * ny + 1.0)
            i = (r1 + x) * 3
            out[i] = int((nx * inv * 0.5 + 0.5) * 255.0)
            out[i + 1] = int((ny * inv * 0.5 + 0.5) * 255.0)
            out[i + 2] = int((nz * inv * 0.5 + 0.5) * 255.0)
    return out


def _b(v):
    return 0 if v < 0 else (255 if v > 255 else int(v))


