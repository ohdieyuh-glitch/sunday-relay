/**
 * EXPORT THE WONDERLAND GEOMETRY CONTRACT INTO THE UNREAL CLIENT.
 *
 * Two artefacts, both generated, both from the same frozen source:
 *
 *   the GOLDEN FIXTURE   what the TypeScript sampler computes, so the C++ port
 *                        can be held against it. Two ports of one algorithm
 *                        drift silently, and the frozen control points make
 *                        that worse rather than better: a divergence shows up
 *                        as the same shape drawn subtly wrong, not as a break.
 *
 *   the CANONICAL SHAPES the control points as compilable C++. The SHAPE is
 *                        static design data the client may hold; the usage
 *                        FIGURES are runtime state that arrives from Relay. A
 *                        world must be able to draw its own empty track before
 *                        the first push, which is why the curve ships and the
 *                        numbers do not.
 *
 * Imported directly rather than shelled out to. An earlier version built its
 * command at run time and the repository boundary scanner refused it — a
 * deployment-capable path has to be statically analyzable, and that rule has
 * already caught the same mistake once in this repository.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  WONDERLAND_COMPOUND_SWOOSH,
  WONDERLAND_SINGLE_SWOOSH,
  WONDERLAND_USAGE_CHANNEL_STYLE,
  WONDERLAND_USAGE_VIEWPORT,
  wonderlandSwooshAt,
} from '../src/relay/mission/wonderland/wonderland-usage-meter';
import type { WonderlandUsageSwoosh } from '../src/relay/mission/wonderland/wonderland-usage-meter';

/**
 * THE ROOT IS THE WORKING DIRECTORY, ASSERTED RATHER THAN ASSUMED.
 *
 * This file is bundled to CommonJS before it runs, so `import.meta.url` is
 * empty by the time it would be read and `__dirname` would name the bundle's
 * home in `generated/` rather than this file's. `process.cwd()` is what the
 * other repository scripts use and what npm guarantees. It is also the one that
 * can be wrong — run from elsewhere it would silently write nothing useful — so
 * the directory it names is CHECKED, and a bad root stops the export instead of
 * leaving the golden fixture quietly stale.
 */
const target = join(process.cwd(), 'wonderland', 'Source', 'Wonderland');
if (!existsSync(target)) {
  console.error(
    `export-wonderland-geometry-fixture: ${target} does not exist.\n` +
      'Run this from the repository root (npm run wonderland:geometry:export).',
  );
  process.exit(1);
}

/** Enough samples to catch a drift, few enough to read in a diff. */
const STEPS = 32;

const shapes: ReadonlyArray<readonly [string, WonderlandUsageSwoosh]> = [
  ['compound', WONDERLAND_COMPOUND_SWOOSH],
  ['single', WONDERLAND_SINGLE_SWOOSH],
];

/* ------------------------------------------------------- the golden fixture */

const rows: string[] = [];
for (const [name, shape] of shapes) {
  for (let step = 0; step <= STEPS; step += 1) {
    const t = step / STEPS;
    const sample = wonderlandSwooshAt(t, shape);
    rows.push(
      [t, sample.x, sample.y, sample.tangentX, sample.tangentY, sample.halfWidth]
        .map((value) => value.toFixed(6))
        .reduce((line, value) => `${line}\t${value}`, name),
    );
  }
}

const fixture = [
  '# WONDERLAND USAGE GEOMETRY — GOLDEN FIXTURE',
  '# GENERATED by scripts/export-wonderland-geometry-fixture.ts. Do not hand-edit.',
  '# Columns: shape<TAB>t<TAB>x<TAB>y<TAB>tangentX<TAB>tangentY<TAB>halfWidth',
  '# Produced by the TypeScript sampler; the Unreal port is held against it by',
  '# wonderland/Tools/geometry-parity-check.sh.',
  ...rows,
  '',
].join('\n');

/* ---------------------------------------------------- the canonical shapes */

const f = (n: number): string => `${n.toFixed(6)}f`;

const shapeBody = (name: string, shape: WonderlandUsageSwoosh): string =>
  [
    `const FWonderlandUsageSwoosh& Wonderland${name}Swoosh()`,
    '{',
    '\tstatic const FWonderlandUsageSwoosh Shape = []{',
    '\t\tFWonderlandUsageSwoosh S;',
    `\t\tS.StartX = ${f(shape.startX)};`,
    `\t\tS.StartY = ${f(shape.startY)};`,
    ...shape.segments.map(
      (s) =>
        `\t\tS.Segments.Add(Seg(${f(s.control1X)}, ${f(s.control1Y)}, ${f(s.control2X)}, ${f(s.control2Y)}, ${f(s.endX)}, ${f(s.endY)}));`,
    ),
    `\t\tS.TailWidth = ${f(shape.tailWidth)};`,
    `\t\tS.TipWidth = ${f(shape.tipWidth)};`,
    `\t\tS.TaperStart = ${f(shape.taperStart)};`,
    `\t\tS.TaperExponent = ${f(shape.taperExponent)};`,
    '\t\treturn S;',
    '\t}();',
    '\treturn Shape;',
    '}',
  ].join('\n');

/* --------------------------------------------------------- the palette */

/**
 * THE SAME COLOURS, PRE-CONVERTED, BECAUSE UNREAL CANNOT READ CSS.
 *
 * The contract states the palette as CSS strings, which is what the browser
 * wants and what a designer can read. A renderer that had to parse `rgba(63,
 * 214, 160, 0.45)` at run time would need a string parser in C++ for no reason,
 * and one that carried a hand-typed copy of the numbers would drift from the
 * approved palette the first time a colour moved.
 *
 * So the conversion happens HERE, once, at export: CSS is parsed, sRGB is
 * linearised, and the client holds finished FLinearColors that were generated
 * from the same constants the browser renders. `--check` fails when they go
 * stale, so a colour changed in the contract and not re-exported is a build
 * failure rather than a HUD that is subtly the wrong green.
 */

interface Rgba {
  readonly r: number;
  readonly g: number;
  readonly b: number;
  readonly a: number;
}

/** Parse the two CSS forms the palette actually uses. Anything else stops. */
function parseCss(value: string): Rgba {
  const hex = /^#([0-9a-f]{6})$/i.exec(value.trim());
  if (hex !== null) {
    const n = Number.parseInt(hex[1], 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  const rgba = /^rgba?\(([^)]+)\)$/i.exec(value.trim());
  if (rgba !== null) {
    const parts = rgba[1].split(',').map((part) => Number.parseFloat(part.trim()));
    if (parts.length >= 3 && parts.slice(0, 3).every(Number.isFinite)) {
      return { r: parts[0], g: parts[1], b: parts[2], a: parts.length > 3 ? parts[3] : 1 };
    }
  }
  // Deliberately fatal. A palette entry this script cannot read is a colour the
  // world would render as something nobody chose, and shipping that quietly is
  // worse than not shipping the export.
  throw new Error(`export-wonderland-geometry-fixture: cannot parse CSS colour ${value}`);
}

/**
 * sRGB channel to linear, by the piecewise sRGB transfer function.
 *
 * Unreal's own FLinearColor::FromSRGBColor uses this curve, so a colour
 * converted here lands where the engine would have put it — and the HUD in the
 * world matches the HUD in the browser rather than being a shade off.
 */
const linear = (channel: number): number => {
  const c = Math.min(1, Math.max(0, channel / 255));
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};

const colourLiteral = (css: string): string => {
  const { r, g, b, a } = parseCss(css);
  return `FLinearColor(${f(linear(r))}, ${f(linear(g))}, ${f(linear(b))}, ${f(a)})`;
};

const paletteBody = (name: string, style: (typeof WONDERLAND_USAGE_CHANNEL_STYLE)['compound_agent']): string =>
  [
    `const FWonderlandUsagePalette& Wonderland${name}Palette()`,
    '{',
    '\tstatic const FWonderlandUsagePalette Palette = []{',
    '\t\tFWonderlandUsagePalette P;',
    `\t\tP.Accent = ${colourLiteral(style.accent)};`,
    `\t\tP.Bright = ${colourLiteral(style.bright)};`,
    `\t\tP.Glow = ${colourLiteral(style.glow)};`,
    `\t\tP.Track = ${colourLiteral(style.track)};`,
    `\t\tP.Emphasis = ${style.emphasis};`,
    '\t\treturn P;',
    '\t}();',
    '\treturn Palette;',
    '}',
  ].join('\n');

/* ------------------------------------------------------------- viewport */

/**
 * The crop, generated for the same reason the shapes are.
 *
 * The window onto the unit box is a product decision — it was measured from the
 * two strokes' actual extent — and a client that carried its own copy would
 * clip a redrawn shape the browser showed whole. Doubles rather than floats
 * here because the mirrored struct is doubles: `d` on a float literal assigned
 * to a double would round twice.
 */
const d = (n: number): string => n.toFixed(6);

const viewport = [
  'const FWonderlandUsageViewport& WonderlandUsageViewport()',
  '{',
  '\tstatic const FWonderlandUsageViewport Window = []{',
  '\t\tFWonderlandUsageViewport V;',
  `\t\tV.X = ${d(WONDERLAND_USAGE_VIEWPORT.x)};`,
  `\t\tV.Y = ${d(WONDERLAND_USAGE_VIEWPORT.y)};`,
  `\t\tV.Width = ${d(WONDERLAND_USAGE_VIEWPORT.width)};`,
  `\t\tV.Height = ${d(WONDERLAND_USAGE_VIEWPORT.height)};`,
  '\t\treturn V;',
  '\t}();',
  '\treturn Window;',
  '}',
].join('\n');

const palette = `${paletteBody('Compound', WONDERLAND_USAGE_CHANNEL_STYLE.compound_agent)}

${paletteBody('Single', WONDERLAND_USAGE_CHANNEL_STYLE.single_agent)}
`;

const generated = `// WONDERLAND USAGE GEOMETRY — THE CANONICAL SHAPES.
//
// GENERATED by scripts/export-wonderland-geometry-fixture.ts from the frozen
// TypeScript contract. DO NOT HAND-EDIT: the control points are founder-frozen
// and pinned by digest on the TypeScript side, and a hand-kept second copy
// would drift while that digest went on passing.
//
// The SHAPE is static design data and belongs in the client. The FIGURES are
// runtime state and arrive from Relay. Confusing the two is how a world ends up
// unable to draw its own empty track before the first push arrives.

#include "WonderlandUsageGeometry.h"

namespace
{
\tFWonderlandSwooshSegment Seg(float C1X, float C1Y, float C2X, float C2Y, float EX, float EY)
\t{
\t\tFWonderlandSwooshSegment Out;
\t\tOut.Control1X = C1X; Out.Control1Y = C1Y;
\t\tOut.Control2X = C2X; Out.Control2Y = C2Y;
\t\tOut.EndX = EX;       Out.EndY = EY;
\t\treturn Out;
\t}
}

${shapeBody('Compound', WONDERLAND_COMPOUND_SWOOSH)}

${shapeBody('Single', WONDERLAND_SINGLE_SWOOSH)}

${palette}
${viewport}
`;

/* --------------------------------------------------------- emit, or verify */

/**
 * `--check` REGENERATES AND COMPARES INSTEAD OF WRITING.
 *
 * The numeric parity harness compiles the C++ sampler and diffs it against the
 * fixture, which proves the two SAMPLERS agree. It cannot prove the fixture is
 * current: both artefacts are generated from the same TypeScript, so a control
 * point edited without a re-export leaves them stale TOGETHER, agreeing
 * perfectly about a shape the product no longer draws. This mode closes that,
 * the same way `julius:harness:check` closes it for the harness manifest.
 */
const artefacts: ReadonlyArray<readonly [string, string]> = [
  ['WonderlandUsageGeometry.golden.tsv', fixture],
  ['WonderlandUsageGeometry.canonical.cpp', generated],
];

const checking = process.argv.includes('--check');
const stale: string[] = [];

for (const [name, content] of artefacts) {
  const path = join(target, name);
  if (!checking) {
    writeFileSync(path, content);
    continue;
  }
  const onDisk = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (onDisk !== content) {
    stale.push(onDisk === null ? `${name} (missing)` : name);
  }
}

if (checking) {
  if (stale.length > 0) {
    console.error(
      `export-wonderland-geometry-fixture --check: stale artefact(s): ${stale.join(', ')}.\n` +
        'The TypeScript geometry moved without a re-export. Run:\n' +
        '  npm run wonderland:geometry:export\n' +
        'and commit the result.',
    );
    process.exit(1);
  }
  console.log(`wonderland geometry artefacts current (${rows.length} samples)`);
} else {
  console.log(`wonderland geometry fixture -> ${rows.length} samples`);
  console.log('wonderland canonical shapes -> WonderlandUsageGeometry.canonical.cpp');
}
