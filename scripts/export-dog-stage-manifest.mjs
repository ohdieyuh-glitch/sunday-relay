#!/usr/bin/env node
/**
 * EXPORT THE DOG STAGE MANIFEST — one serialized form, two runtimes.
 *
 * The Relay app and the Unreal world are separate runtimes. The TypeScript
 * stage table in `src/relay/mission/wonderland/wonderland-dog-stage.ts` cannot
 * be reached from a scene component in PIE, so the world derives the same
 * contract independently from its own beat fold. That is one source of truth
 * PER RUNTIME, both derived from the founder's 2026-09-15 specification — which
 * is fine right up until they drift, at which point the Relay UI and the world
 * disagree about what the Dog is doing and neither one is obviously wrong.
 *
 * This script writes the contract to `wonderland/Wonderland.DogStages.json` so
 * both sides have something to check themselves against:
 *
 *   TypeScript  `wonderland-dog-stage-manifest.test.ts` fails when this file is
 *               stale, exactly as the Julius harness manifest works.
 *   Unreal      a C++ test may read the same JSON and assert its beat -> act
 *               table agrees, rather than restating the spec a third time.
 *
 * Run after changing the stage table:  node scripts/export-dog-stage-manifest.mjs
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const DOG_STAGE_MANIFEST_PATH = join(here, '..', 'wonderland', 'Wonderland.DogStages.json');

/**
 * Build the manifest from the live table.
 *
 * Takes the module as an argument rather than importing it, so the test can
 * hand in the same module it asserts against and the two cannot diverge.
 */
export function buildDogStageManifest(stageModule) {
  const {
    WONDERLAND_MISSION_STAGES,
    WONDERLAND_LOCKED_STAGES,
    WONDERLAND_STAGE_PRESENTATION,
    WONDERLAND_ACTIVITY_STAGE,
  } = stageModule;

  return {
    $comment:
      'GENERATED by scripts/export-dog-stage-manifest.mjs. Do not hand-edit. ' +
      'The canonical Relay Dog mission-stage contract, shared by the Relay app and the Unreal world.',
    schema: 'relay-wonderland-dog-stage.v1',
    lockedStages: [...WONDERLAND_LOCKED_STAGES],
    stages: WONDERLAND_MISSION_STAGES.map((stage) => {
      const presentation = WONDERLAND_STAGE_PRESENTATION[stage];
      return presentation.kind === 'inherit'
        ? { stage, presentation: 'inherit', because: presentation.because }
        : {
          stage,
          presentation: 'staged',
          animationId: presentation.animationId,
          prop: presentation.prop,
          locomotion: presentation.locomotion,
          emission: presentation.emission,
          contractPresent: presentation.contractPresent,
          headTracksContract: presentation.headTracksContract,
        };
    }),
    activityToStage: { ...WONDERLAND_ACTIVITY_STAGE },
  };
}

export const renderDogStageManifest = (manifest) => `${JSON.stringify(manifest, null, 2)}\n`;

// Executed directly: write the file. Imported by the test: export only.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const stageModule = await import('../src/relay/mission/wonderland/wonderland-dog-stage.ts');
  writeFileSync(DOG_STAGE_MANIFEST_PATH, renderDogStageManifest(buildDogStageManifest(stageModule)), 'utf8');
  process.stdout.write(`wrote ${DOG_STAGE_MANIFEST_PATH}\n`);
}
