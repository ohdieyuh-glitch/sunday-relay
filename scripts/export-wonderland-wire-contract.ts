/**
 * EXPORT THE WIRE → USTRUCT MAPPING A CLIENT HAS TO IMPLEMENT.
 *
 * `Wonderland.Build.cs` has depended on `Json` and `JsonUtilities` since the
 * module existed and no C++ file uses them: the decode is unwritten. It is
 * worth writing the CONTRACT down before the code, because the two shapes
 * differ in two places and both differences fail quietly rather than loudly.
 *
 * A nullable field crosses as a value or `null` and lands in a carrier struct
 * with its own `bKnown`; a decoder that maps by name alone leaves the carrier
 * zero-filled, which reads as "Relay did not say" for a figure Relay did say.
 * And Relay's tokens are snake_case where Unreal's members are PascalCase; an
 * unmatched member leaves the ordinal at 0, which in every nullable-mirroring
 * enum here is `Unobserved` — so the world looks like Relay is silent instead
 * of like a decoder that is broken.
 *
 * GENERATED, LIKE THE ORDERING FIXTURE AND FOR THE SAME REASON. This table
 * records what the contract IS rather than what anybody remembers it to be, and
 * `--check` fails when the two have parted company. It is derived from the same
 * parity tables `wonderland-cpp-parity.test.ts` holds the real headers to, so
 * it cannot name a field the headers lack or miss one they have without that
 * test failing first.
 *
 * IT CLAIMS NOTHING ABOUT UNREAL. No engine has run here. This says what the
 * two shapes are and where they differ; what a decoder does about it is the
 * engine session's to write and to prove.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  WONDERLAND_WIRE_DECODE_RULES,
  wonderlandWireContract,
} from '../src/relay/mission/wonderland/wonderland-wire-contract';
import type { WonderlandWireContract } from '../src/relay/mission/wonderland/wonderland-wire-contract';

/** Render the contract as the document. Pure, so the test renders the same bytes. */
export function renderWonderlandWireContract(contract: WonderlandWireContract): string {
  const lines: string[] = [];
  const carriersByStruct = new Map<string, string[]>();
  for (const carrier of contract.carriers) {
    const list = carriersByStruct.get(carrier.cppStruct) ?? [];
    list.push(carrier.field);
    carriersByStruct.set(carrier.cppStruct, list);
  }

  lines.push('# Wonderland — the wire → USTRUCT decode contract');
  lines.push('');
  lines.push('**GENERATED by `npm run wonderland:wire:export`. Do not edit by hand.**');
  lines.push('`npm run wonderland:wire:check` fails when it is stale.');
  lines.push('');
  lines.push('This is what a client must do to Relay\'s JSON before it is a USTRUCT.');
  lines.push('It describes two SHAPES and where they differ. It says nothing about what');
  lines.push('any Unreal API does — no engine has run in the environment that produced it.');
  lines.push('');
  lines.push(`Schema: \`${contract.schemaVersion}\``);
  lines.push('');
  lines.push('## The two differences that fail quietly');
  lines.push('');
  lines.push('**ABSENCE.** TypeScript has `null`; Unreal\'s numerics, strings and bools do');
  lines.push('not. Every nullable field crosses as a value or `null` and lands in one of');
  lines.push(`the carriers (${contract.carrierTypes.map((t) => `\`${t}\``).join(', ')}), each`);
  lines.push('`{ bKnown, Value }`. **A decoder must set `bKnown`.** A zero-filled carrier');
  lines.push('reads as "Relay did not say" — so a mapping that only matches names turns');
  lines.push('every real figure into an unknown, silently.');
  lines.push('');
  lines.push('**VOCABULARY.** Relay\'s tokens are `snake_case` or `SCREAMING_SNAKE`;');
  lines.push('Unreal\'s members are `PascalCase`. `independent_review` is not');
  lines.push('`IndependentReview` to anything comparing strings. An unmatched token leaves');
  lines.push('the ordinal at 0, and 0 in every nullable-mirroring enum below is');
  lines.push('`Unobserved` — so the world looks like Relay is reporting nothing rather');
  lines.push('than like a decoder that is broken.');
  lines.push('');
  lines.push('The rules, as the contract names them:');
  lines.push('');
  for (const rule of WONDERLAND_WIRE_DECODE_RULES) lines.push(`- \`${rule}\``);
  lines.push('');
  lines.push(`## Fields that need a carrier (${contract.carriers.length})`);
  lines.push('');
  lines.push('The JSON key is the TypeScript field name. Every one of these arrives as a');
  lines.push('bare value or `null` and must be widened into the carrier its struct declares.');
  lines.push('');
  lines.push('| struct | TypeScript | JSON keys |');
  lines.push('|---|---|---|');
  for (const entry of contract.structs) {
    const fields = carriersByStruct.get(entry.cppStruct);
    if (fields === undefined) continue;
    lines.push(`| \`${entry.cppStruct}\` | \`${entry.tsInterface}\` | ${fields.map((f) => `\`${f}\``).join(', ')} |`);
  }
  lines.push('');
  lines.push(`## Enum token mapping (${contract.enums.length} enums)`);
  lines.push('');
  lines.push('`nullable` means Relay can report nothing for it, so ordinal 0 is reachable');
  lines.push('and means exactly that. A token this table does not list is one Relay does');
  lines.push('not send; leave the zero member rather than inventing a match.');
  lines.push('');
  for (const entry of contract.enums) {
    lines.push(`### \`${entry.cppEnum}\``);
    lines.push('');
    lines.push(`From \`${entry.source}\`. Nullable: **${entry.nullable ? 'yes' : 'no'}**. Zero member: \`${entry.zeroMember}\`.`);
    lines.push('');
    lines.push('| wire token | C++ member |');
    lines.push('|---|---|');
    for (const member of entry.members) {
      lines.push(`| \`${member.token}\` | \`${member.cppMember}\` |`);
    }
    lines.push('');
  }
  lines.push(`## Structs that cross whole (${contract.structs.length})`);
  lines.push('');
  lines.push('| C++ | TypeScript |');
  lines.push('|---|---|');
  for (const entry of contract.structs) {
    lines.push(`| \`${entry.cppStruct}\` | \`${entry.tsInterface}\` |`);
  }
  lines.push('');
  return `${lines.join('\n')}`;
}

/** Which enums the decoder actually needs a table for. */
const DECODED_ENUMS = [
  'EWonderlandJuliusState',
  'EWonderlandJuliusStateSource',
  'EWonderlandWorkerRole',
  'EWonderlandActivitySignal',
] as const;

/**
 * The token tables, as C++ the decoder links against.
 *
 * GENERATED for the same reason the ordering cases are: this is a mapping that
 * exists twice, and a hand-written copy drifts silently in the direction where
 * every token still LOOKS plausible. A token missing from a table is refused by
 * name at runtime rather than landing on ordinal 0, so the failure mode of a
 * stale table is a loud refusal — but the table should not go stale at all.
 */
export function renderWonderlandWireTables(contract: WonderlandWireContract): string {
  const lines: string[] = [];
  lines.push('// GENERATED by `npm run wonderland:wire:export`. DO NOT EDIT.');
  lines.push('//');
  lines.push('// Every Relay token for every enum the wire decoder reads, paired with the');
  lines.push('// C++ member it names. Derived from the same parity tables the headers are');
  lines.push('// held to, so a member here always exists.');
  lines.push('//');
  lines.push('// A token NOT in these tables is refused by name. It never lands on ordinal 0:');
  lines.push('// zero is `Unobserved` in every one of these, and a decoder that fell back to');
  lines.push('// it would make a broken client look like a silent Relay.');
  lines.push('');
  lines.push('#include "WonderlandWireDecode.h"');
  lines.push('');

  for (const name of DECODED_ENUMS) {
    const entry = contract.enums.find((e) => e.cppEnum === name);
    if (entry === undefined) {
      throw new Error(`export-wonderland-wire-contract: ${name} is not in the parity table`);
    }
    lines.push(`// ${entry.cppEnum} — from ${entry.source}. Zero member: ${entry.zeroMember}.`);
    lines.push(`static const FWonderlandWireToken ${entry.cppEnum}Tokens[] = {`);
    for (const member of entry.members) {
      lines.push(`\t{ "${member.token}", static_cast<uint8>(${entry.cppEnum}::${member.cppMember}) },`);
    }
    lines.push('};');
    lines.push('');
  }

  lines.push('const FWonderlandWireEnumTable WonderlandWireEnumTables[] = {');
  for (const name of DECODED_ENUMS) {
    const entry = contract.enums.find((e) => e.cppEnum === name)!;
    lines.push(`\t{ "${entry.cppEnum}", ${entry.cppEnum}Tokens, ${entry.members.length}, ${entry.nullable ? 'true' : 'false'} },`);
  }
  lines.push('};');
  lines.push('');
  lines.push(`const int32 WonderlandWireEnumTableCount = ${DECODED_ENUMS.length};`);
  lines.push('');
  return `${lines.join('\n')}`;
}

export const WONDERLAND_WIRE_TABLES_PATH = join('wonderland', 'Source', 'Wonderland', 'WonderlandWireDecode.tables.cpp');

export const WONDERLAND_WIRE_CONTRACT_PATH = join('docs', 'handoffs', 'WONDERLAND_WIRE_CONTRACT.md');

function main(): void {
  const root = process.cwd();
  // A wrong root would silently write the document somewhere nobody reads and
  // report success, so the anchor is asserted rather than assumed.
  if (!existsSync(join(root, 'docs', 'handoffs'))) {
    console.error(
      `export-wonderland-wire-contract: ${join(root, 'docs', 'handoffs')} does not exist.\n` +
        'Run this from the repository root (npm run wonderland:wire:export).',
    );
    process.exit(1);
  }

  const contract = wonderlandWireContract();
  const artefacts: readonly { readonly path: string; readonly body: string }[] = [
    { path: join(root, WONDERLAND_WIRE_CONTRACT_PATH), body: renderWonderlandWireContract(contract) },
    { path: join(root, WONDERLAND_WIRE_TABLES_PATH), body: renderWonderlandWireTables(contract) },
  ];
  const generated = artefacts.map((a) => a.body).join('');
  const path = join(root, WONDERLAND_WIRE_CONTRACT_PATH);

  if (process.argv.includes('--check')) {
    const onDisk = artefacts
      .map((a) => (existsSync(a.path) ? readFileSync(a.path, 'utf8') : null))
      .join('');
    if (onDisk !== generated) {
      console.error(
        'export-wonderland-wire-contract --check: the wire contract is stale.\n' +
          'A struct, a nullable field or an enum moved without a re-export. Run:\n' +
          '  npm run wonderland:wire:export\n' +
          'READ THE DIFF — it is a change to what a client has to decode.',
      );
      process.exit(1);
    }
    console.log(`wonderland wire contract current (${wonderlandWireContract().carriers.length} carriers)`);
    return;
  }

  for (const artefact of artefacts) writeFileSync(artefact.path, artefact.body);
  void path;
  console.log(
    `wonderland wire contract -> ${contract.structs.length} structs, ` +
      `${contract.carriers.length} carrier fields, ${contract.enums.length} enums`,
  );
}

// Only when RUN, not when the test imports the renderer.
if (process.argv[1]?.includes('export-wonderland-wire-contract')) main();
