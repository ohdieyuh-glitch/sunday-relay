/**
 * EXPORT THE ORDERING RULE'S BEHAVIOUR AS A CASE TABLE THE CLIENT IS HELD TO.
 *
 * The ordering rule is the one piece of this seam a client genuinely has to
 * re-implement. Everything else can be computed once in TypeScript and pushed
 * already decided — but which of several envelopes arriving over a real network
 * a world should apply is a question only the receiver can answer, and it has to
 * answer it in C++ with no Relay in the process.
 *
 * Two implementations of one rule drift silently, and this rule drifts in the
 * worst possible direction: a client that got the revision-before-sequence
 * ordering slightly wrong would look correct for every ordinary stream and go
 * backwards only during a reconnect onto a stale replica — the exact moment
 * anybody was watching.
 *
 * So the cases are GENERATED by running the real TypeScript, and the C++ is
 * diffed against what it produced. The table records what TypeScript DOES, not
 * what anybody expected it to do: the script builds a matrix of cursors and
 * envelopes and writes down whatever comes back, so a deliberate change to the
 * rule shows up as a fixture diff to review rather than as a test somebody has
 * to remember to update.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  applyWonderlandOrdering,
  openWonderlandCursor,
} from '../src/relay/mission/wonderland/wonderland-ordering';
import type { WonderlandCursor } from '../src/relay/mission/wonderland/wonderland-ordering';
import { wonderlandEnvelope } from '../src/relay/mission/wonderland/wonderland-envelope';
import type { WonderlandEnvelope } from '../src/relay/mission/wonderland/wonderland-envelope';

const target = join(process.cwd(), 'wonderland', 'Source', 'Wonderland');
if (!existsSync(target)) {
  console.error(
    `export-wonderland-ordering-fixture: ${target} does not exist.\n` +
      'Run this from the repository root (npm run wonderland:ordering:export).',
  );
  process.exit(1);
}

/* ------------------------------------------------------------- the matrix */

const PROJECT = 'project-alpha';
const JULIUS = 'julius-1';
const RUN = 'run-1';

/** A cursor at a stated position, reached the way a real one would be. */
function cursorAt(input: {
  readonly sequence: number;
  readonly revision: number;
  readonly fromSnapshot: boolean;
  readonly bound: boolean;
}): WonderlandCursor {
  const open = openWonderlandCursor({
    projectId: PROJECT,
    juliusInstanceId: input.bound ? JULIUS : null,
    runId: input.bound ? RUN : null,
  });
  if (input.sequence === 0 && input.revision === 0 && !input.fromSnapshot) return open;
  // Reached by ACCEPTING an envelope rather than by hand, so the fixture can
  // never describe a cursor the rule itself could not produce.
  const { cursor } = applyWonderlandOrdering(
    open,
    envelope({
      eventId: 'seed',
      sequence: input.sequence,
      revision: input.revision,
      runId: input.bound ? RUN : null,
      juliusInstanceId: input.bound ? JULIUS : null,
    }),
  );
  return input.fromSnapshot
    ? Object.freeze({ ...cursor, revisionFromSnapshot: true })
    : cursor;
}

function envelope(input: {
  readonly eventId: string;
  readonly sequence: number;
  readonly revision: number;
  readonly projectId?: string;
  readonly runId?: string | null;
  readonly juliusInstanceId?: string | null;
}): WonderlandEnvelope {
  return wonderlandEnvelope({
    eventId: input.eventId,
    projectId: input.projectId ?? PROJECT,
    juliusInstanceId: input.juliusInstanceId === undefined ? JULIUS : input.juliusInstanceId,
    runId: input.runId === undefined ? RUN : input.runId,
    state: 'coding',
    stateSource: 'julius_run_state',
    sequence: input.sequence,
    revision: input.revision,
    occurredAt: '2026-09-08T00:00:00.000Z',
  });
}

interface Case {
  readonly name: string;
  readonly cursor: WonderlandCursor;
  readonly envelope: WonderlandEnvelope;
}

const cases: Case[] = [];
const add = (name: string, cursor: WonderlandCursor, env: WonderlandEnvelope): void => {
  cases.push({ name, cursor, envelope: env });
};

/* The identity refusals, each against a cursor that has learned its identity. */
const bound = cursorAt({ sequence: 5, revision: 3, fromSnapshot: false, bound: true });
add('foreign_project', bound, envelope({ eventId: 'e1', sequence: 9, revision: 9, projectId: 'project-beta' }));
add('foreign_julius', bound, envelope({ eventId: 'e2', sequence: 9, revision: 9, juliusInstanceId: 'julius-2' }));
add('foreign_run', bound, envelope({ eventId: 'e3', sequence: 9, revision: 9, runId: 'run-2' }));
add('unbound_julius_accepted', cursorAt({ sequence: 5, revision: 3, fromSnapshot: false, bound: false }),
  envelope({ eventId: 'e4', sequence: 9, revision: 9, juliusInstanceId: 'julius-9' }));
add('null_julius_on_envelope_accepted', bound,
  envelope({ eventId: 'e5', sequence: 9, revision: 9, juliusInstanceId: null }));
add('null_run_on_envelope_accepted', bound,
  envelope({ eventId: 'e6', sequence: 9, revision: 9, runId: null }));

/* The structural refusals. */
add('negative_sequence', bound, envelope({ eventId: 'e7', sequence: -1, revision: 9 }));
add('negative_revision', bound, envelope({ eventId: 'e8', sequence: 9, revision: -1 }));
add('empty_event_id', bound, envelope({ eventId: '', sequence: 9, revision: 9 }));

/* The duplicate, which needs a cursor that has seen the id. */
const seen = applyWonderlandOrdering(
  openWonderlandCursor({ projectId: PROJECT, juliusInstanceId: JULIUS, runId: RUN }),
  envelope({ eventId: 'repeated', sequence: 4, revision: 2 }),
).cursor;
add('duplicate_event_id', seen, envelope({ eventId: 'repeated', sequence: 9, revision: 9 }));
add('same_id_lower_position_still_duplicate', seen, envelope({ eventId: 'repeated', sequence: 1, revision: 1 }));

/* The two staleness axes, and the tie that only a snapshot refuses. */
add('stale_revision', bound, envelope({ eventId: 'e9', sequence: 99, revision: 2 }));
add('revision_tie_from_events_ok', bound, envelope({ eventId: 'e10', sequence: 6, revision: 3 }));
add('revision_tie_from_snapshot_stale',
  cursorAt({ sequence: 5, revision: 3, fromSnapshot: true, bound: true }),
  envelope({ eventId: 'e11', sequence: 6, revision: 3 }));
add('revision_ahead_from_snapshot_ok',
  cursorAt({ sequence: 5, revision: 3, fromSnapshot: true, bound: true }),
  envelope({ eventId: 'e12', sequence: 6, revision: 4 }));
add('stale_sequence', bound, envelope({ eventId: 'e13', sequence: 5, revision: 9 }));
add('sequence_behind_but_revision_ahead', bound, envelope({ eventId: 'e14', sequence: 1, revision: 9 }));
// THE CASE THAT SEPARATES THE TWO CHECKS, and the reason it is called out.
// Every other stale envelope gets the same verdict whichever axis is consulted
// first: one that is behind on only one of them falls through to the other
// either way. Only an envelope behind on BOTH distinguishes the orderings —
// revision-first calls it `stale_revision`, sequence-first calls it
// `stale_sequence` — and without this case a port could check them in the wrong
// order and pass every test. A deliberate reordering of the C++ was not caught
// until this existed.
add('behind_on_both_reports_revision', bound, envelope({ eventId: 'e22', sequence: 3, revision: 2 }));
add('behind_on_both_at_snapshot_tie',
  cursorAt({ sequence: 5, revision: 3, fromSnapshot: true, bound: true }),
  envelope({ eventId: 'e23', sequence: 2, revision: 3 }));

/* Acceptance, and the gap it may or may not record. */
add('applied_next', bound, envelope({ eventId: 'e15', sequence: 6, revision: 4 }));
add('applied_with_gap', bound, envelope({ eventId: 'e16', sequence: 12, revision: 4 }));
add('first_ever_no_gap',
  openWonderlandCursor({ projectId: PROJECT }),
  envelope({ eventId: 'e17', sequence: 40, revision: 7 }));
add('applied_learns_identity',
  openWonderlandCursor({ projectId: PROJECT }),
  envelope({ eventId: 'e18', sequence: 1, revision: 1 }));
add('applied_does_not_lower_revision', bound, envelope({ eventId: 'e19', sequence: 6, revision: 3 }));
add('accepted_clears_snapshot_flag',
  cursorAt({ sequence: 5, revision: 3, fromSnapshot: true, bound: true }),
  envelope({ eventId: 'e20', sequence: 6, revision: 5 }));
add('zero_sequence_first_event',
  openWonderlandCursor({ projectId: PROJECT }),
  envelope({ eventId: 'e21', sequence: 0, revision: 0 }));

/* ------------------------------------------------------------ the emitter */

const q = (field: string, value: string | null): string =>
  value === null ? '' : `\t\t\t${field} = Known(TEXT(${JSON.stringify(value)}));\n`;
const b = (value: boolean): string => (value ? 'true' : 'false');

const cursorLiteral = (prefix: string, cursor: WonderlandCursor): string =>
  `\t\t\t${prefix}.SchemaVersion = TEXT(${JSON.stringify(cursor.schemaVersion)});\n` +
  `\t\t\t${prefix}.ProjectId = TEXT(${JSON.stringify(cursor.projectId)});\n` +
  q(`${prefix}.JuliusInstanceId`, cursor.juliusInstanceId) +
  q(`${prefix}.RunId`, cursor.runId) +
  `\t\t\t${prefix}.Sequence = ${cursor.sequence};\n` +
  `\t\t\t${prefix}.Revision = ${cursor.revision};\n` +
  `\t\t\t${prefix}.bRevisionFromSnapshot = ${b(cursor.revisionFromSnapshot)};\n` +
  q(`${prefix}.LastEventId`, cursor.lastEventId) +
  q(`${prefix}.LastAppliedAtIso`, cursor.lastAppliedAtIso) +
  `\t\t\t${prefix}.Applied = ${cursor.applied};\n` +
  `\t\t\t${prefix}.Duplicates = ${cursor.duplicates};\n` +
  `\t\t\t${prefix}.StaleSequences = ${cursor.staleSequences};\n` +
  `\t\t\t${prefix}.StaleRevisions = ${cursor.staleRevisions};\n` +
  `\t\t\t${prefix}.ForeignProjects = ${cursor.foreignProjects};\n` +
  `\t\t\t${prefix}.ForeignJulius = ${cursor.foreignJulius};\n` +
  `\t\t\t${prefix}.ForeignRuns = ${cursor.foreignRuns};\n` +
  `\t\t\t${prefix}.Malformed = ${cursor.malformed};\n` +
  `\t\t\t${prefix}.Gaps = ${cursor.gaps};\n`;

const envelopeLiteral = (env: WonderlandEnvelope): string =>
  `\t\t\tCase.Envelope.SchemaVersion = TEXT(${JSON.stringify(env.schemaVersion)});\n` +
  `\t\t\tCase.Envelope.EventId = TEXT(${JSON.stringify(env.eventId)});\n` +
  `\t\t\tCase.Envelope.ProjectId = TEXT(${JSON.stringify(env.projectId)});\n` +
  q('Case.Envelope.JuliusInstanceId', env.juliusInstanceId) +
  q('Case.Envelope.RunId', env.runId) +
  `\t\t\tCase.Envelope.OccurredAt = TEXT(${JSON.stringify(env.occurredAt)});\n` +
  `\t\t\tCase.Envelope.Sequence = ${env.sequence};\n` +
  `\t\t\tCase.Envelope.Revision = ${env.revision};\n` +
  `\t\t\tCase.Envelope.bTerminal = ${b(env.terminal)};\n`;

const PASCAL: Readonly<Record<string, string>> = {
  applied: 'Applied',
  duplicate: 'Duplicate',
  stale_sequence: 'StaleSequence',
  stale_revision: 'StaleRevision',
  foreign_project: 'ForeignProject',
  foreign_julius: 'ForeignJulius',
  foreign_run: 'ForeignRun',
  malformed: 'Malformed',
};

const blocks = cases.map((entry) => {
  const { verdict, cursor } = applyWonderlandOrdering(entry.cursor, entry.envelope);
  return (
    '\t\t{\n' +
    '\t\t\tFWonderlandOrderingCase Case;\n' +
    `\t\t\tCase.Name = TEXT(${JSON.stringify(entry.name)});\n` +
    cursorLiteral('Case.Before', entry.cursor) +
    envelopeLiteral(entry.envelope) +
    `\t\t\tCase.Expected = EWonderlandOrderingVerdict::${PASCAL[verdict]};\n` +
    cursorLiteral('Case.After', cursor) +
    '\t\t\tOut.Add(Case);\n' +
    '\t\t}'
  );
});

const generated = `// WONDERLAND ORDERING — THE CASE TABLE.
//
// GENERATED by scripts/export-wonderland-ordering-fixture.ts by running the
// REAL TypeScript rule. DO NOT HAND-EDIT: the whole point is that this records
// what \`wonderlandOrderingVerdict\` and \`applyWonderlandOrdering\` actually do,
// so an edit here would be a claim about behaviour nothing checked.
//
// A deliberate change to the rule shows up as a diff in this file, to be read
// and approved, rather than as a test somebody has to remember to update.
//
// ${cases.length} cases. Regenerate with: npm run wonderland:ordering:export

#include "WonderlandOrdering.h"

namespace
{
\tFWonderlandText Known(const FString& Value)
\t{
\t\tFWonderlandText Text;
\t\tText.bKnown = true;
\t\tText.Value = Value;
\t\treturn Text;
\t}
}

const TArray<FWonderlandOrderingCase>& WonderlandOrderingCases()
{
\tstatic const TArray<FWonderlandOrderingCase> Cases = []{
\t\tTArray<FWonderlandOrderingCase> Out;
${blocks.join('\n')}
\t\treturn Out;
\t}();
\treturn Cases;
}
`;

const path = join(target, 'WonderlandOrdering.cases.cpp');
const checking = process.argv.includes('--check');
if (checking) {
  const onDisk = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (onDisk !== generated) {
    console.error(
      'export-wonderland-ordering-fixture --check: the case table is stale.\n' +
        'The TypeScript ordering rule moved without a re-export. Run:\n' +
        '  npm run wonderland:ordering:export\n' +
        'READ THE DIFF before committing it — it is a change to how a world decides\n' +
        'which events to apply.',
    );
    process.exit(1);
  }
  console.log(`wonderland ordering cases current (${cases.length} cases)`);
} else {
  writeFileSync(path, generated);
  console.log(`wonderland ordering cases -> ${cases.length} cases`);
}
